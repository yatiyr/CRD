// kir_autotune — ADR-0098 §4 · AS-2b: the OFFLINE auto-scheduler CLI. Runs the CKIR GEMM schedule search on the GPU for a set of
// shapes and emits the checked-in tuning DB (`ckir_tuning_db.inc`) that `select_schedule` replays deterministically — "tune
// offline, replay from the DB, never at runtime" (ADR-0098). Usage:
//   kir_autotune [SIZE ...] [out.inc]
// SIZE args are square-GEMM sizes (default 512 1024 2048); a trailing non-numeric arg is the output path (else stdout).
#include <crd/core/parse_integer.hpp>
#include <crd/kir/cuda/autotune_cuda.hpp>
#include <crd/memory/allocators/tlsf_allocator.hpp>
#include <crd/platform/arguments.hpp>

#include <cstdio>
#include <cstring>

namespace
{

struct Shape
{
    int m;
    int n;
    int k;
};

// One shape argument: "MxNxK" (rectangular) or a bare "S" (square S x S x S), each side a decimal in [1, 2^31 - 1]
// (crd-core's parse). False for anything else, which is the output path.
bool shape_of(const char* text, Shape& out)
{
    crd::u64 sides[3] = {};
    const char* at = text;
    const char* const end = text + std::strlen(text);
    int count = 0;
    while (true)
    {
        const void* const found = std::memchr(at, 'x', static_cast<crd::usize>(end - at));
        const char* const stop = found != nullptr ? static_cast<const char*>(found) : end;
        if (count == 3 || !crd::parse_u64(at, stop, 0x7FFFFFFFULL, sides[count]) || sides[count] == 0U)
        {
            return false;
        }
        ++count;
        if (stop == end)
        {
            break;
        }
        at = stop + 1;
    }
    if (count == 2)
    {
        return false;
    }
    const crd::u64 m = sides[0];
    const crd::u64 n = count == 1 ? m : sides[1];
    const crd::u64 k = count == 1 ? m : sides[2];
    out = {static_cast<int>(m), static_cast<int>(n), static_cast<int>(k)};
    return true;
}

} // namespace

int main(int argc, char** argv)
{
    const crd::platform::Arguments arguments(argc, argv); // UTF-8 on every platform (crd/platform/arguments.hpp)
    argc = arguments.count();
    argv = arguments.values();
    crd::memory::TlsfAllocator alloc(512U << 20U);
    crd::kir::KirBackendCuda   cu(&alloc);
    if (!cu.valid())
    {
        std::fprintf(stderr, "kir_autotune: no CUDA device/driver — cannot tune.\n");
        return 1;
    }

    Shape       shapes[64];
    int         nshapes = 0;
    const char* outpath = nullptr;
    for (int i = 1; i < argc; ++i)
    {
        Shape shape{};
        if (!shape_of(argv[i], shape))
        {
            outpath = argv[i];
        }
        else if (nshapes < 64)
        {
            shapes[nshapes++] = shape;
        }
    }
    if (nshapes == 0)
    {
        // a default LADDER: square + rectangular (MLP-shaped) so the DB generalises, not just square.
        const Shape def[] = {{512, 512, 512}, {1024, 1024, 1024}, {2048, 2048, 2048}, {4096, 4096, 4096},
                             {2048, 512, 1024}, {4096, 1024, 256}, {1024, 4096, 512}};
        for (const Shape& d : def)
        {
            if (nshapes < 64)
            {
                shapes[nshapes++] = d;
            }
        }
    }

    crd::kir::AutotuneResult results[64];
    int                      nres = 0;
    for (int i = 0; i < nshapes; ++i)
    {
        const int m = shapes[i].m;
        const int n = shapes[i].n;
        const int k = shapes[i].k;
        std::fprintf(stderr, "[kir_autotune] tuning GEMM %dx%dx%d ...\n", m, n, k);
        const crd::kir::AutotuneResult r = crd::kir::autotune_contract(cu, m, n, k, 16, true, &alloc);
        if (!r.ok)
        {
            std::fprintf(stderr, "[kir_autotune]   no valid schedule (skipped)\n");
            continue;
        }
        const double gflops = 2.0 * static_cast<double>(m) * n * k / (r.ms * 1.0e6);
        std::fprintf(stderr,
                     "[kir_autotune]   winner %.3f ms (%.0f GFLOP/s) BM%d BN%d BK%d TM%d TN%d NT%d DB%d; "
                     "naive %.3f ms (%.1fx); %d/%d correct\n",
                     r.ms, gflops, r.sched.bm, r.sched.bn, r.sched.bk, r.sched.tm, r.sched.tn, r.sched.nt,
                     r.sched.double_buffer ? 1 : 0, r.naive_ms, r.naive_ms > 0.0 ? r.naive_ms / r.ms : 0.0, r.correct,
                     r.measured);
        results[nres++] = r;
    }

    std::FILE* f = (outpath != nullptr) ? std::fopen(outpath, "w") : stdout;
    if (f == nullptr)
    {
        std::fprintf(stderr, "kir_autotune: cannot open %s\n", outpath);
        return 2;
    }
    std::fprintf(f, "// ckir_tuning_db.inc - the CKIR AUTO-TUNED SCHEDULE DATABASE (ADR-0098 sec.4, AS-2). GENERATED by kir_autotune\n");
    std::fprintf(f, "// from on-GPU measurements; DO NOT edit by hand -- re-run kir_autotune. Included inside crd::kir by ckir_tile.hpp.\n");
    std::fprintf(f, "// Row: { op, DEVICE, M, N, K, { kind, BM,BN,BK, WM,WN,WNITER, TM,TN, NT, double_buffer, fma } }.\n");
    const char* dev = cu.device(); // AS-6a: the GPU arch this DB was tuned on (e.g. "sm_89") — the per-device replay key
    for (int i = 0; i < nres; ++i)
    {
        const crd::kir::AutotuneResult& r = results[i];
        std::fprintf(f, "{ KOp::Contract, \"%s\", \"%s\", %d, %d, %d, { Sched::WarpTiled, %d, %d, %d, %d, %d, %d, %d, %d, %d, %s, %s } },\n",
                     dev, crd::kir::tuning_env(), r.m, r.n, r.k, r.sched.bm, r.sched.bn, r.sched.bk, r.sched.wm, r.sched.wn, r.sched.wniter, r.sched.tm,
                     r.sched.tn, r.sched.nt, r.sched.double_buffer ? "true" : "false", r.sched.fma ? "true" : "false");
    }
    if (outpath != nullptr)
    {
        std::fclose(f);
        std::fprintf(stderr, "[kir_autotune] wrote %d entries -> %s\n", nres, outpath);
    }
    return 0;
}
