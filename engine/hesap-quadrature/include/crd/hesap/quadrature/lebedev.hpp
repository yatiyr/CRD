// Lebedev cubature over the unit sphere: result = sum_i w_i f(x_i, y_i, z_i) ~ int_{S^2} f dOmega (= 4*pi for
// f==1). f: callable (T,T,T)->T evaluated on unit vectors. degree must be one of {5, 7, 11, 17}; else BadInput.
template <typename T, typename F> [[nodiscard]] QuadResult<T> integrate_lebedev(F&& f, int degree)
{
    const T* data = nullptr;
    int n = 0;
    switch (degree)
    {
        case 5:
            data = detail::Lebedev5<T>::kData;
            n = detail::Lebedev5<T>::kNpoints;
            break;
        case 7:
            data = detail::Lebedev7<T>::kData;
            n = detail::Lebedev7<T>::kNpoints;
            break;
        case 11:
            data = detail::Lebedev11<T>::kData;
            n = detail::Lebedev11<T>::kNpoints;
            break;
        case 17:
            data = detail::Lebedev17<T>::kData;
            n = detail::Lebedev17<T>::kNpoints;
            break;
        default:
            return QuadResult<T>{T{0}, T{0}, 0, 0, QuadStatus::BadInput, false};
    }
    T acc = T{0};
    for (int i = 0; i < n; ++i)
    {
        acc += data[i * 4 + 3] * f(data[i * 4 + 0], data[i * 4 + 1], data[i * 4 + 2]);
    }
    QuadResult<T> r;
    r.value = acc;
    r.eval_count = static_cast<crd::u32>(n);
    return r;
}

