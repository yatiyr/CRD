// -----------------------------------------------------------------------
// TtTensor<T> — a tensor in tensor-train format: d cores, core k of shape
// (r_{k-1}, n_k, r_k) stored row-major, r_0 = r_d = 1; A(i_1..i_d) =
// G_1[i_1] * G_2[i_2] * ... * G_d[i_d] (a product of rank-slices).
//
// OWNS its cores in one contiguous Array<T> (per-core offsets) — returned
// objects never hold borrowed lifetimes (the v14-g HyperTree scar). Move-only;
// allocator-bound at construction (IAllocator propagation, no defaults).
// -----------------------------------------------------------------------
template <typename T> class TtTensor
{
    static_assert(std::is_floating_point_v<T>, "TtTensor<T>: real f32/f64 in v1");

public:
    explicit TtTensor(crd::memory::IAllocator* alloc) noexcept : m_data(alloc)
    {
        CRD_ASSERT_MSG(alloc != nullptr, "TtTensor: null allocator");
    }

    TtTensor(const TtTensor&) = delete;
    TtTensor& operator=(const TtTensor&) = delete;
    TtTensor(TtTensor&&) noexcept = default;
    TtTensor& operator=(TtTensor&&) noexcept = default;

    // (Re)allocate cores for `shape` (d dims) and `ranks` (d+1 entries,
    // ranks[0] == ranks[d] == 1). Core contents uninitialized.
    [[nodiscard]] TensorStatus init(crd::containers::ConstSpan<crd::u64> shape,
                                    crd::containers::ConstSpan<crd::u64> ranks)
    {
        if (shape.size() == 0U || shape.size() > kMaxRank || ranks.size() != shape.size() + 1U)
        {
            return TensorStatus::BadInput;
        }
        if (ranks[0] != 1U || ranks[shape.size()] != 1U)
        {
            return TensorStatus::BadInput;
        }
        const crd::u32 d = static_cast<crd::u32>(shape.size());
        crd::u64 total = 0;
        crd::u64 off[kMaxRank + 1U];
        for (crd::u32 k = 0; k < d; ++k)
        {
            if (shape[k] == 0U || ranks[k] == 0U || ranks[k + 1U] == 0U)
            {
                return TensorStatus::BadInput;
            }
            const crd::u64 cs = ranks[k] * shape[k] * ranks[k + 1U];
            if (cs / ranks[k] / shape[k] != ranks[k + 1U] || total > ~crd::u64{0} - cs)
            {
                return TensorStatus::BadInput; // element-count overflow
            }
            off[k] = total;
            total += cs;
        }
        off[d] = total;
        if (!m_data.try_reserve(total))
        {
            return TensorStatus::AllocFailed;
        }
        m_data.resize(total);
        m_dims = d;
        for (crd::u32 k = 0; k < d; ++k)
        {
            m_shape[k] = shape[k];
            m_ranks[k] = ranks[k];
            m_offset[k] = off[k];
        }
        m_ranks[d] = 1U;
        m_offset[d] = total;
        return TensorStatus::Ok;
    }

    [[nodiscard]] crd::u32 dims() const noexcept { return m_dims; }
    [[nodiscard]] crd::u64 shape(crd::u32 k) const noexcept
    {
        CRD_ASSERT_MSG(k < m_dims, "TtTensor::shape: dim out of range");
        return m_shape[k];
    }
    // rank(k) for k in [0, dims()] — rank(0) == rank(dims()) == 1.
    [[nodiscard]] crd::u64 rank(crd::u32 k) const noexcept
    {
        CRD_ASSERT_MSG(k <= m_dims, "TtTensor::rank: edge out of range");
        return m_ranks[k];
    }
    [[nodiscard]] crd::containers::ConstSpan<crd::u64> shape() const noexcept { return {m_shape, m_dims}; }
    [[nodiscard]] crd::containers::ConstSpan<crd::u64> ranks() const noexcept
    {
        return {m_ranks, static_cast<crd::usize>(m_dims) + 1U};
    }
    [[nodiscard]] T* core(crd::u32 k) noexcept
    {
        CRD_ASSERT_MSG(k < m_dims, "TtTensor::core: dim out of range");
        return m_data.data() + m_offset[k];
    }
    [[nodiscard]] const T* core(crd::u32 k) const noexcept
    {
        CRD_ASSERT_MSG(k < m_dims, "TtTensor::core: dim out of range");
        return m_data.data() + m_offset[k];
    }
    [[nodiscard]] crd::u64 core_size(crd::u32 k) const noexcept
    {
        CRD_ASSERT_MSG(k < m_dims, "TtTensor::core_size: dim out of range");
        return m_offset[k + 1U] - m_offset[k];
    }
    // Total TT parameter count (the compression numerator: dense elems / this).
    [[nodiscard]] crd::u64 param_count() const noexcept { return m_dims > 0U ? m_offset[m_dims] : 0U; }
    [[nodiscard]] crd::u64 max_rank() const noexcept
    {
        crd::u64 r = 1;
        for (crd::u32 k = 0; k <= m_dims; ++k)
        {
            if (m_ranks[k] > r)
            {
                r = m_ranks[k];
            }
        }
        return r;
    }
    [[nodiscard]] crd::u64 element_count() const noexcept
    {
        crd::u64 n = 1;
        for (crd::u32 k = 0; k < m_dims; ++k)
        {
            n *= m_shape[k];
        }
        return n;
    }
    [[nodiscard]] crd::memory::IAllocator* allocator() const noexcept { return m_data.allocator(); }

private:
    crd::containers::Array<T> m_data; // all cores, contiguous (owned)
    crd::u32 m_dims = 0;
    crd::u64 m_shape[kMaxRank] = {};
    crd::u64 m_ranks[kMaxRank + 1U] = {};
    crd::u64 m_offset[kMaxRank + 1U] = {};
};

// info structs (NotConverged rides here — TensorStatus is frozen this slice)
struct MaxvolInfo
{
    crd::u32 iters = 0;
    bool converged = false; // max |A*Ahat^-1| <= tol reached within max_iters
    bool singular = false;  // a zero pivot was substituted during LU init
};

template <typename T> struct TtCrossInfo
{
    T val_error = T(0);      // final validation relative error
    crd::u64 evals = 0;      // fiber function evaluations (validation counted separately)
    crd::u64 val_evals = 0;  // validation-set function evaluations (one-time)
    crd::u32 sweeps = 0;     // sweep pairs executed
    bool converged = false;  // val_error < tol within max_sweeps
};

template <typename T> struct TtCrossParams
{
    crd::u64 max_rank = 8;   // TT rank cap per edge (clamped to unfolding sizes)
    crd::u32 max_sweeps = 8; // bounded iteration: L2R+R2L sweep pairs
    T tol = T(1e-10);        // validation relative-error convergence target
    crd::u64 val_size = 200; // validation points (deterministic from `seed`)
    crd::u64 seed = 0x7714CCULL; // PhiloxRng seed (pivot starts + validation)
};

