// crd-hesap-tensor — v14-k: Decompositions II — TENSOR TRAINS.
//
// TtTensor<T> (owned cores — never borrowed lifetimes, the v14-g scar) +
//   tt_svd       dense tensor -> TT at tolerance/rank cap (Oseledets 2011,
//                Alg. 1: sequential unfolding SVD, delta = tol*||A||_F/sqrt(d-1)
//                tail-energy chop) — reuses hesap-dense svd() (SANITY #8);
//   tt_round     rank re-compression (Oseledets 2011, Alg. 2: right-to-left QR
//                orthogonalization, left-to-right SVD truncation) — reuses
//                hesap-dense factor_qr/apply_q + svd();
//   tt_add / tt_hadamard / tt_dot / tt_norm / tt_contract   TT algebra
//                (block concat / slice-wise Kronecker / two-gemm-per-core
//                bilinear contraction / materialization via hesap-dense gemm);
//   tt_eval / tt_eval_many / tt_eval_lerp   ALLOCATION-FREE evaluation of a
//                single element / index batch / multilinear-interpolated point
//                (caller workspace, size = tt_eval_workspace(tt) = 2*max_rank,
//                checked). tt_eval_lerp(TT of a grid LUT) equals multilinear
//                interpolation of the DENSE grid (a tensor-product linear
//                functional factors through the cores) — the v13-interp LUT
//                compression story;
//   maxvol       the Goreinov-Oseledets-Savostyanov-Tyrtyshnikov-Zamarashkin
//                quasi-max-volume submatrix ("How to Find a Good Submatrix",
//                2010). Source of truth: transliterated from tntorch/maxvol.py
//                `py_maxvol` (verbatim in tntorch from A. Mikhalev's maxvolpy),
//                reconstructed + verified in numpy first
//                (scripts/v14k_tt_oracle.py). LU-pivot init, C = A*Ahat^-1 via
//                two row-wise triangular solves, argmax + rank-1 update loop —
//                BOUNDED by max_iters, tol-terminated;
//   tt_cross     TT from FUNCTION EVALUATIONS without materializing the tensor
//                (Oseledets-Tyrtyshnikov 2010 TT-cross; the fixed-rank ALS
//                QR+maxvol sweep scheme of tntorch/cross.py, verified in numpy
//                first). Deterministic: pivot starts + validation points from
//                PhiloxRng(seed) — same seed => bit-identical result. Sweeps
//                BOUNDED by max_sweeps; convergence = validation error < tol.
//
// Error contract: fallible ops return TensorStatus (never throw). TensorStatus
// is frozen (tensor.hpp is not edited this slice), so NotConverged rides the
// info structs (TtCrossInfo::converged / MaxvolInfo::converged) — the
// batched_svd_small info-lane precedent. Programmer errors are CRD_ASSERT.
//
// Determinism: every routine here is SERIAL in v1 (deliberate — the per-op
// working sets are rank-bounded and small; batch parallelism belongs to the
