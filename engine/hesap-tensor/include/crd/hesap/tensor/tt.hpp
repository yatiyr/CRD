// -----------------------------------------------------------------------
// tt_cross — build a TT approximation of f over an integer index grid WITHOUT
// materializing the tensor. f: callable T(ConstSpan<u64> idx) with
// idx.size() == shape.size(). Fixed-rank ALS sweeps with QR + maxvol pivot
// selection (the tntorch/cross.py scheme, oracle-verified):
//   left-to-right:  fibers -> left-unfold QR -> maxvol -> core = Q*Qhat^-1,
//                   nested left index sets grow one mode;
//   right-to-left:  mirrored on the right unfolding;
//   first core = raw fibers (the cross interpolation is exact on the sets).
// Deterministic: initial right sets from PhiloxRng(seed, stream 0), the
// validation set from PhiloxRng(seed, stream 1) — same seed => bit-identical
// TT (gated). BOUNDED: max_sweeps sweep pairs; converged = validation
// relative error < tol (info->converged; the status stays Ok — the
// batched_svd_small info precedent, TensorStatus is frozen this slice).
// -----------------------------------------------------------------------
template <typename T, typename F>
[[nodiscard]] TensorStatus tt_cross(crd::memory::IAllocator* alloc, crd::containers::ConstSpan<crd::u64> shape,
                                    F&& f, const TtCrossParams<T>& params, TtTensor<T>& out,
                                    TtCrossInfo<T>* info) noexcept
{
    namespace dn = crd::hesap::dense;
    if (alloc == nullptr || shape.size() == 0U || shape.size() > kMaxRank || params.max_rank == 0U ||
        params.max_sweeps == 0U || params.val_size == 0U || !(params.tol > T(0)))
    {
        return TensorStatus::BadInput;
    }
    const crd::u32 d = static_cast<crd::u32>(shape.size());
    for (crd::u32 k = 0; k < d; ++k)
    {
        if (shape[k] == 0U)
        {
            return TensorStatus::BadInput;
        }
    }
    TtCrossInfo<T> local;
    ttdetail::CrossLayout lay;
    ttdetail::cross_layout(shape, params.max_rank, lay);
    // ---- pools (pre-sized ONCE; reserve-before-spans) ---------------------
    crd::containers::Array<crd::u64> ipool(alloc);
    const crd::u64 val_idx_total = params.val_size * d;
    if (!ipool.try_reserve(lay.lset_total + lay.rset_total + val_idx_total + kMaxRank + lay.max_rank))
    {
        return TensorStatus::AllocFailed;
    }
    ipool.resize(lay.lset_total + lay.rset_total + val_idx_total + kMaxRank + lay.max_rank);
    crd::u64* lsets = ipool.data();
    crd::u64* rsets = ipool.data() + lay.lset_total;
    crd::u64* val_idx = rsets + lay.rset_total;
    crd::u64* idxbuf = val_idx + val_idx_total;
    crd::u64* selbuf = idxbuf + kMaxRank;
    crd::containers::Array<T> fpool(alloc);
    const crd::u64 qcap = lay.max_fiber;  // thin Q (rows x r): rows*r == fiber size
    const crd::u64 btcap = lay.max_fiber; // solve RHS (r x rows) / transposed fiber
    const crd::u64 fpool_total = lay.core_total + lay.max_fiber + qcap + btcap + params.val_size * 2U +
                                 2U * lay.max_rank + lay.max_fiber /*colbuf*/;
    if (!fpool.try_reserve(fpool_total))
    {
        return TensorStatus::AllocFailed;
    }
    fpool.resize(fpool_total);
    T* cores = fpool.data();
    T* fiber = cores + lay.core_total;
    T* qbuf = fiber + lay.max_fiber;
    T* solvebuf = qbuf + qcap;
    T* val_true = solvebuf + btcap;
    T* val_pred = val_true + params.val_size;
    T* evwork = val_pred + params.val_size;
    T* colbuf = evwork + 2U * lay.max_rank;
    // ---- deterministic starts: nested random right sets -------------------
    {
        crd::hesap::stats::PhiloxRng rng(params.seed, 0);
        // the shared random matrix (maxR rows x d cols; col n ~ U[0, shape[n+1]))
        // materialized column-nested exactly like the oracle: rsets[j] row b =
        // randmat[b][j .. d-2]
        crd::u64 randmat[kMaxRank]; // one row at a time
        for (crd::u64 b = 0; b < lay.max_rank; ++b)
        {
            for (crd::u32 n = 0; n + 1U < d; ++n)
            {
                randmat[n] = rng.next_below(shape[n + 1U]);
            }
            for (crd::u32 j = 0; j + 1U < d; ++j)
            {
                if (b < lay.rs[j + 1U])
                {
                    const crd::u64 cols = d - 1U - j;
                    for (crd::u64 t = 0; t < cols; ++t)
                    {
                        rsets[lay.rset_off[j] + b * cols + t] = randmat[j + t];
                    }
                }
            }
        }
    }
    // ---- deterministic validation set -------------------------------------
    {
        crd::hesap::stats::PhiloxRng rng(params.seed, 1);
        for (crd::u64 p = 0; p < params.val_size; ++p)
        {
            for (crd::u32 k = 0; k < d; ++k)
            {
                val_idx[p * d + k] = rng.next_below(shape[k]);
            }
        }
        for (crd::u64 p = 0; p < params.val_size; ++p)
        {
            val_true[p] = f(crd::containers::ConstSpan<crd::u64>{val_idx + p * d, d});
        }
        local.val_evals = params.val_size;
    }
    T val_norm = ttdetail::fro_norm(val_true, params.val_size);
    if (val_norm == T(0))
    {
        val_norm = T(1);
    }
    // ---- fiber evaluation (idx = lset row ++ i ++ rset row) ---------------
    const auto eval_fibers = [&](crd::u32 j) noexcept
    {
        const crd::u64 rl = lay.rs[j];
        const crd::u64 n = shape[j];
        const crd::u64 rr = lay.rs[j + 1U];
        const crd::u64 rcols = d - 1U - j;
        for (crd::u64 a2 = 0; a2 < rl; ++a2)
        {
            const crd::u64* lrow = lsets + lay.lset_off[j] + a2 * j;
            for (crd::u64 t = 0; t < j; ++t)
            {
                idxbuf[t] = lrow[t];
            }
            for (crd::u64 i = 0; i < n; ++i)
            {
                idxbuf[j] = i;
                for (crd::u64 b = 0; b < rr; ++b)
                {
                    const crd::u64* rrow = rsets + lay.rset_off[j] + b * rcols;
                    for (crd::u64 t = 0; t < rcols; ++t)
                    {
                        idxbuf[j + 1U + t] = rrow[t];
                    }
                    fiber[(a2 * n + i) * rr + b] =
                        f(crd::containers::ConstSpan<crd::u64>{idxbuf, d});
                }
            }
        }
        local.evals += rl * n * rr;
    };
    // thin-QR of an (m x r) buffer, m >= r, into qbuf (m x r orthonormal cols)
    const auto thin_q = [&](const T* m, crd::u64 rows, crd::u64 r) noexcept -> TensorStatus
    {
        dn::QR<T> qr(alloc, static_cast<crd::usize>(rows), static_cast<crd::usize>(r));
        dn::Matrix<T>& p = qr.packed();
        for (crd::u64 i = 0; i < rows; ++i)
        {
            for (crd::u64 j2 = 0; j2 < r; ++j2)
            {
                p.at(static_cast<crd::usize>(i), static_cast<crd::usize>(j2)) = m[i * r + j2];
            }
        }
        dn::factor_qr(qr);
        ttdetail::form_thin_q(qr, qbuf, rows, r, colbuf);
        return TensorStatus::Ok;
    };
    // core := Q @ inv(Q[sel]) via LU solve of Qsel^T X = Q^T (recomputed, not
    // the maxvol-iterated coefficients — the tntorch lstsq accuracy choice)
    const auto interp_core = [&](crd::u64 rows, crd::u64 r, T* dst) noexcept -> TensorStatus
    {
        dn::LU<T> lu(alloc, static_cast<crd::usize>(r));
        dn::Matrix<T>& p = lu.packed();
        for (crd::u64 i = 0; i < r; ++i)
        {
            for (crd::u64 j2 = 0; j2 < r; ++j2)
            {
                // Qsel^T: entry (i, j2) = Q[sel[j2]][i]
                p.at(static_cast<crd::usize>(i), static_cast<crd::usize>(j2)) = qbuf[selbuf[j2] * r + i];
            }
        }
        dn::factor_lu(lu, alloc);
        if (lu.info() != 0U)
        {
            return TensorStatus::Unsupported; // maxvol guarantees nonsingular; defensive
        }
        for (crd::u64 i = 0; i < r; ++i) // B = Q^T (r x rows)
        {
            for (crd::u64 t = 0; t < rows; ++t)
            {
                solvebuf[i * rows + t] = qbuf[t * r + i];
            }
        }
        dn::MatrixView<T, dn::Layout::RowMajor> bview = ttdetail::mview_mut(solvebuf, r, rows);
        dn::solve_lu(lu, bview);
        for (crd::u64 t = 0; t < rows; ++t) // dst = X^T (rows x r)
        {
            for (crd::u64 i = 0; i < r; ++i)
            {
                dst[t * r + i] = solvebuf[i * rows + t];
            }
        }
        return TensorStatus::Ok;
    };
    // ---- sweeps ------------------------------------------------------------
    TensorStatus st = TensorStatus::Ok;
    for (crd::u32 sweep = 0; sweep < params.max_sweeps && !local.converged; ++sweep)
    {
        // left-to-right: set cores 0..d-2, grow lsets 1..d-1
        for (crd::u32 j = 0; j + 1U < d; ++j)
        {
            eval_fibers(j);
            const crd::u64 rl = lay.rs[j];
            const crd::u64 n = shape[j];
            const crd::u64 rr = lay.rs[j + 1U];
            const crd::u64 rows = rl * n;
            st = thin_q(fiber, rows, rr);
            if (st != TensorStatus::Ok)
            {
                return st;
            }
            MaxvolInfo mvi;
            st = maxvol<T>(alloc, qbuf, rows, rr, T(1.05), 200U,
                           crd::containers::Span<crd::u64>{selbuf, static_cast<crd::usize>(rr)}, nullptr,
                           &mvi);
            if (st != TensorStatus::Ok)
            {
                return st;
            }
            st = interp_core(rows, rr, cores + lay.core_off[j]);
            if (st != TensorStatus::Ok)
            {
                return st;
            }
            // lsets[j+1] row s = lsets[j][sel/n] ++ (sel % n)
            for (crd::u64 s = 0; s < rr; ++s)
            {
                const crd::u64 a2 = selbuf[s] / n;
                const crd::u64 i = selbuf[s] % n;
                const crd::u64* srcrow = lsets + lay.lset_off[j] + a2 * j;
                crd::u64* dstrow = lsets + lay.lset_off[j + 1U] + s * (j + 1U);
                for (crd::u64 t = 0; t < j; ++t)
                {
                    dstrow[t] = srcrow[t];
                }
                dstrow[j] = i;
            }
        }
        // right-to-left: set cores d-1..1, grow rsets d-2..0
        for (crd::u32 j = d - 1U; j >= 1U; --j)
        {
            eval_fibers(j);
            const crd::u64 rl = lay.rs[j];
            const crd::u64 n = shape[j];
            const crd::u64 rr = lay.rs[j + 1U];
            const crd::u64 rows = n * rr;
            // right unfolding transposed: (n*rr x rl); fiber is (rl x n*rr)
            for (crd::u64 a2 = 0; a2 < rl; ++a2)
            {
                for (crd::u64 t = 0; t < rows; ++t)
                {
                    solvebuf[t * rl + a2] = fiber[a2 * rows + t];
                }
            }
            st = thin_q(solvebuf, rows, rl);
            if (st != TensorStatus::Ok)
            {
                return st;
            }
            MaxvolInfo mvi;
            st = maxvol<T>(alloc, qbuf, rows, rl, T(1.05), 200U,
                           crd::containers::Span<crd::u64>{selbuf, static_cast<crd::usize>(rl)}, nullptr,
                           &mvi);
            if (st != TensorStatus::Ok)
            {
                return st;
            }
            // core j = (Q inv(Q[sel]))^T -> (rl x n*rr) directly
            {
                dn::LU<T> lu(alloc, static_cast<crd::usize>(rl));
                dn::Matrix<T>& p = lu.packed();
                for (crd::u64 i = 0; i < rl; ++i)
                {
                    for (crd::u64 j2 = 0; j2 < rl; ++j2)
                    {
                        p.at(static_cast<crd::usize>(i), static_cast<crd::usize>(j2)) =
                            qbuf[selbuf[j2] * rl + i];
                    }
                }
                dn::factor_lu(lu, alloc);
                if (lu.info() != 0U)
                {
                    return TensorStatus::Unsupported;
                }
                T* dst = cores + lay.core_off[j];
                for (crd::u64 i = 0; i < rl; ++i) // RHS = Q^T (rl x rows)
                {
                    for (crd::u64 t = 0; t < rows; ++t)
                    {
                        dst[i * rows + t] = qbuf[t * rl + i];
                    }
                }
                dn::MatrixView<T, dn::Layout::RowMajor> bview = ttdetail::mview_mut(dst, rl, rows);
                dn::solve_lu(lu, bview);
            }
            // rsets[j-1] row s = (sel / rr) ++ rsets[j][sel % rr]
            const crd::u64 rcols = d - 1U - j;
            for (crd::u64 s = 0; s < rl; ++s)
            {
                const crd::u64 i = selbuf[s] / rr;
                const crd::u64 b = selbuf[s] % rr;
                const crd::u64* srcrow = rsets + lay.rset_off[j] + b * rcols;
                crd::u64* dstrow = rsets + lay.rset_off[j - 1U] + s * (rcols + 1U);
                dstrow[0] = i;
                for (crd::u64 t = 0; t < rcols; ++t)
                {
                    dstrow[1U + t] = srcrow[t];
                }
            }
        }
        // first core = raw fibers at the final left/right sets
        eval_fibers(0);
        {
            T* dst = cores + lay.core_off[0];
            const crd::u64 cs = lay.rs[0] * shape[0] * lay.rs[1];
            for (crd::u64 i = 0; i < cs; ++i)
            {
                dst[i] = fiber[i];
            }
        }
        local.sweeps = sweep + 1U;
        // validation error via the (not yet copied-out) cores
        {
            T errsq = T(0);
            for (crd::u64 p = 0; p < params.val_size; ++p)
            {
                const crd::u64* ix = val_idx + p * d;
                T* v = evwork;
                T* w = evwork + lay.max_rank;
                const crd::u64 r1 = lay.rs[1];
                const T* g = cores + lay.core_off[0] + ix[0] * r1;
                for (crd::u64 t = 0; t < r1; ++t)
                {
                    v[t] = g[t];
                }
                for (crd::u32 k = 1; k < d; ++k)
                {
                    const crd::u64 rl = lay.rs[k];
                    const crd::u64 rr = lay.rs[k + 1U];
                    const crd::u64 n = shape[k];
                    const T* gk = cores + lay.core_off[k] + ix[k] * rr;
                    for (crd::u64 t = 0; t < rr; ++t)
                    {
                        T s = T(0);
                        for (crd::u64 x = 0; x < rl; ++x)
                        {
                            s = std::fma(v[x], gk[x * n * rr + t], s);
                        }
                        w[t] = s;
                    }
                    T* tmp = v;
                    v = w;
                    w = tmp;
                }
                const T dv = v[0] - val_true[p];
                errsq = std::fma(dv, dv, errsq);
            }
            local.val_error = std::sqrt(errsq) / val_norm;
            if (local.val_error < params.tol)
            {
                local.converged = true;
            }
        }
    }
    // ---- copy out ----------------------------------------------------------
    st = out.init(shape, {lay.rs, static_cast<crd::usize>(d) + 1U});
    if (st != TensorStatus::Ok)
    {
        return st;
    }
    for (crd::u32 k = 0; k < d; ++k)
    {
        const T* src = cores + lay.core_off[k];
        T* dst = out.core(k);
        for (crd::u64 i = 0; i < out.core_size(k); ++i)
        {
            dst[i] = src[i];
        }
    }
    if (info != nullptr)
    {
        *info = local;
    }
    return TensorStatus::Ok;
}

