// -----------------------------------------------------------------------
// maxvol — quasi-maximum-volume row subset of a tall matrix.
//
// Given A (n_rows x r, row-major, n_rows >= r), selects r rows such that the
// spanned submatrix Ahat has quasi-maximal volume: on exit every entry of
// C = A * Ahat^-1 satisfies |C_ij| <= tol (when converged). rows_out receives
// the r selected 0-based row indices; coeff (optional, may be null) receives
// C (n_rows x r, row-major; C[rows_out] == I).
//
// Faithful port of tntorch/maxvol.py `py_maxvol` (maxvolpy; the
// Goreinov-Oseledets algorithm), reconstructed + verified in numpy first —
// see scripts/v14k_tt_oracle.py. Deterministic: LU pivots and the argmax use
// first-max-wins tie rules (fixed scan order). BOUNDED: at most max_iters
// swap iterations; info->converged reports the tol termination.
//
// HOME-> hesap-dense: the tall-matrix partial-pivot LU init (rectangular
// getrf) is inlined here; hesap-dense's LU is square-only today.
// -----------------------------------------------------------------------
template <typename T>
[[nodiscard]] TensorStatus maxvol(crd::memory::IAllocator* alloc, const T* a, crd::u64 n_rows, crd::u64 r,
                                  T tol, crd::u32 max_iters, crd::containers::Span<crd::u64> rows_out,
                                  T* coeff, MaxvolInfo* info) noexcept
{
    if (a == nullptr || alloc == nullptr || r == 0U || n_rows < r || rows_out.size() != r ||
        max_iters == 0U)
    {
        return TensorStatus::BadInput;
    }
    if (tol < T(1))
    {
        tol = T(1);
    }
    MaxvolInfo local;
    if (n_rows == r) // square: the only volume-r submatrix is A itself
    {
        for (crd::u64 i = 0; i < r; ++i)
        {
            rows_out[i] = i;
            if (coeff != nullptr)
            {
                for (crd::u64 j = 0; j < r; ++j)
                {
                    coeff[i * r + j] = i == j ? T(1) : T(0);
                }
            }
        }
        local.converged = true;
        if (info != nullptr)
        {
            *info = local;
        }
        return TensorStatus::Ok;
    }
    // ---- LU with partial pivoting on a copy of the TALL matrix ----------
    crd::containers::Array<T> work(alloc);
    const crd::u64 c_size = n_rows * r;
    if (!work.try_reserve(c_size /*lu*/ + c_size /*C*/ + r /*y*/ + r /*z*/))
    {
        return TensorStatus::AllocFailed;
    }
    work.resize(c_size * 2U + r * 2U);
    T* lu = work.data();
    T* c = work.data() + c_size;
    T* ybuf = work.data() + c_size * 2U;
    T* zbuf = ybuf + r;
    crd::containers::Array<crd::u64> idxbuf(alloc);
    if (!idxbuf.try_reserve(n_rows + r))
    {
        return TensorStatus::AllocFailed;
    }
    idxbuf.resize(n_rows + r);
    crd::u64* index = idxbuf.data();
    crd::u64* ipiv = idxbuf.data() + n_rows;
    for (crd::u64 i = 0; i < c_size; ++i)
    {
        lu[i] = a[i];
    }
    for (crd::u64 j = 0; j < r; ++j)
    {
        crd::u64 p = j;
        T best = lu[j * r + j] < T(0) ? -lu[j * r + j] : lu[j * r + j];
        for (crd::u64 i = j + 1U; i < n_rows; ++i)
        {
            const T v = lu[i * r + j] < T(0) ? -lu[i * r + j] : lu[i * r + j];
            if (v > best) // strictly greater: lowest row wins ties (deterministic)
            {
                best = v;
                p = i;
            }
        }
        ipiv[j] = p;
        if (p != j)
        {
            for (crd::u64 t = 0; t < r; ++t)
            {
                const T tmp = lu[j * r + t];
                lu[j * r + t] = lu[p * r + t];
                lu[p * r + t] = tmp;
            }
        }
        T piv = lu[j * r + j];
        if (piv == T(0))
        {
            local.singular = true; // rank-deficient input; keep bounded on 1.0
            piv = T(1);
        }
        const T inv = T(1) / piv;
        for (crd::u64 i = j + 1U; i < n_rows; ++i)
        {
            const T l = lu[i * r + j] * inv;
            lu[i * r + j] = l;
            for (crd::u64 t = j + 1U; t < r; ++t)
            {
                lu[i * r + t] = std::fma(-l, lu[j * r + t], lu[i * r + t]);
            }
        }
    }
    for (crd::u64 i = 0; i < n_rows; ++i)
    {
        index[i] = i;
    }
    for (crd::u64 i = 0; i < r; ++i) // LAPACK ipiv replay -> selected row ids
    {
        const crd::u64 tmp = index[i];
        index[i] = index[ipiv[i]];
        index[ipiv[i]] = tmp;
    }
    // ---- C = A * U^-1 * L1^-1 (Ahat = A[index[:r]] = L1*U) ---------------
    for (crd::u64 row = 0; row < n_rows; ++row)
    {
        for (crd::u64 j = 0; j < r; ++j) // y * U = a_row  (forward over columns)
        {
            T s = a[row * r + j];
            for (crd::u64 p = 0; p < j; ++p)
            {
                s = std::fma(-ybuf[p], lu[p * r + j], s);
            }
            ybuf[j] = s / lu[j * r + j];
        }
        for (crd::u64 jj = r; jj-- > 0U;) // z * L1 = y  (unit lower, backward)
        {
            T s = ybuf[jj];
            for (crd::u64 p = jj + 1U; p < r; ++p)
            {
                s = std::fma(-zbuf[p], lu[p * r + jj], s);
            }
            zbuf[jj] = s;
        }
        for (crd::u64 j = 0; j < r; ++j)
        {
            c[row * r + j] = zbuf[j];
        }
    }
    // ---- swap loop: argmax |C|, swap the row in, rank-1 update -----------
    for (crd::u32 it = 0; it < max_iters; ++it)
    {
        crd::u64 brow = 0;
        crd::u64 bslot = 0;
        T bval = T(0);
        for (crd::u64 i = 0; i < c_size; ++i) // row-major first-max tie rule
        {
            const T v = c[i] < T(0) ? -c[i] : c[i];
            if (v > bval)
            {
                bval = v;
                brow = i / r;
                bslot = i % r;
            }
        }
        if (!(bval > tol))
        {
            local.converged = true;
            break;
        }
        index[bslot] = brow;
        const T pivot = c[brow * r + bslot];
        const T inv = T(1) / pivot;
        for (crd::u64 j = 0; j < r; ++j) // row of the swap (minus e_slot)
        {
            zbuf[j] = c[brow * r + j];
        }
        zbuf[bslot] -= T(1);
        for (crd::u64 i = 0; i < n_rows; ++i) // C -= C[:,slot] outer zbuf / pivot
        {
            const T ci = c[i * r + bslot] * inv;
            for (crd::u64 j = 0; j < r; ++j)
            {
                c[i * r + j] = std::fma(-ci, zbuf[j], c[i * r + j]);
            }
        }
        local.iters = it + 1U;
    }
    for (crd::u64 i = 0; i < r; ++i)
    {
        rows_out[i] = index[i];
    }
    if (coeff != nullptr)
    {
        for (crd::u64 i = 0; i < c_size; ++i)
        {
            coeff[i] = c[i];
        }
    }
    if (info != nullptr)
    {
        *info = local;
    }
    return TensorStatus::Ok;
}

// -----------------------------------------------------------------------
// tt_svd — dense (contiguous) tensor -> TT at relative tolerance `tol` with
// optional rank cap (max_rank == 0: uncapped). Error contract (gated):
// ||A - TT||_F <= tol * ||A||_F. Exactly the oracle's np_tt_svd.
// -----------------------------------------------------------------------
template <typename T>
[[nodiscard]] TensorStatus tt_svd(crd::memory::IAllocator* alloc, TensorView<const T> a, T tol,
                                  crd::u64 max_rank, TtTensor<T>& out) noexcept
{
    namespace dn = crd::hesap::dense;
    if (alloc == nullptr || a.rank() == 0U || tol < T(0))
    {
        return TensorStatus::BadInput;
    }
    if (!a.is_contiguous())
    {
        return TensorStatus::NotContiguous;
    }
    const crd::u32 d = a.rank();
    const crd::u64 total = a.size();
    if (total == 0U)
    {
        return TensorStatus::BadInput;
    }
    if (d == 1U) // a vector IS its own single core (1, n, 1)
    {
        const crd::u64 shp[1] = {a.shape(0)};
        const crd::u64 rks[2] = {1U, 1U};
        const TensorStatus st = out.init({shp, 1}, {rks, 2});
        if (st != TensorStatus::Ok)
        {
            return st;
        }
        for (crd::u64 i = 0; i < shp[0]; ++i)
        {
            out.core(0)[i] = a.data()[i];
        }
        return TensorStatus::Ok;
    }
    const T nrm = ttdetail::fro_norm(a.data(), total);
    const T delta = tol * nrm / std::sqrt(static_cast<T>(d - 1U));
    // carry buffer C (sizes never grow across steps: r <= r_prev * n_k)
    crd::containers::Array<T> carry(alloc);
    if (!carry.try_reserve(total))
    {
        return TensorStatus::AllocFailed;
    }
    carry.resize(total);
    for (crd::u64 i = 0; i < total; ++i)
    {
        carry.data()[i] = a.data()[i];
    }
    crd::containers::Array<T> corebuf(alloc); // appended cores (offsets tracked)
    crd::u64 core_off[kMaxRank + 1U] = {};
    crd::u64 ranks[kMaxRank + 1U] = {};
    ranks[0] = 1U;
    crd::u64 rest = total / a.shape(0);
    crd::u64 r_prev = 1U;
    for (crd::u32 k = 0; k < d - 1U; ++k)
    {
        const crd::u64 m = r_prev * a.shape(k);
        crd::u64 r = 0;
        const crd::u64 old = static_cast<crd::u64>(corebuf.size());
        if (rest >= 2U * m)
        {
            // WIDE unfolding fast path (the tt_svd hot case: the first unfolds
            // are m x m*rest_ratio with rest_ratio up to n^{d-1}): QR-first, the
            // dgesdd trick. C = R^T Q^T from QR(C^T); SVD(R^T) = U S W^T gives
            // C's left vectors U and singular values DIRECTLY; the carry needs
            // no Q: U_r^T C = S_r V_r^T exactly. Cost: one tall QR (2*rest*m^2,
            // SIMD panel) + an m x m SVD + one (r x m)@(m x rest) gemm — vs the
            // full tall bidiagonalization + rotation accumulation into a
            // rest x m U (measured 0.53x vs torch/MKL at 32^4 BEFORE this path;
            // the fix flipped every tt_svd row — see the v14-k bench doc).
            dn::QR<T> qr(alloc, static_cast<crd::usize>(rest), static_cast<crd::usize>(m));
            {
                dn::Matrix<T>& p = qr.packed();
                const T* src = carry.data();
                for (crd::u64 i = 0; i < m; ++i)
                {
                    for (crd::u64 j = 0; j < rest; ++j)
                    {
                        p.at(static_cast<crd::usize>(j), static_cast<crd::usize>(i)) = src[i * rest + j];
                    }
                }
            }
            dn::factor_qr(qr);
            dn::Matrix<T> rt(alloc, static_cast<crd::usize>(m), static_cast<crd::usize>(m)); // R^T (lower)
            for (crd::u64 i = 0; i < m; ++i)
            {
                for (crd::u64 j = 0; j <= i; ++j)
                {
                    rt.at(static_cast<crd::usize>(i), static_cast<crd::usize>(j)) =
                        qr.packed().at(static_cast<crd::usize>(j), static_cast<crd::usize>(i));
                }
            }
            dn::SVD<T> f = dn::svd<T>(alloc, rt);
            r = ttdetail::rank_chop(f.s.data(), static_cast<crd::u64>(f.s.size()), delta, max_rank);
            if (!corebuf.try_reserve(old + m * r))
            {
                return TensorStatus::AllocFailed;
            }
            corebuf.resize(old + m * r);
            for (crd::u64 i = 0; i < m; ++i)
            {
                for (crd::u64 j = 0; j < r; ++j)
                {
                    corebuf.data()[old + i * r + j] =
                        f.u.at(static_cast<crd::usize>(i), static_cast<crd::usize>(j));
                }
            }
            // carry := U_r^T @ C  (r x rest; = S_r V_r^T) — gemm into a temp,
            // then copy back (C is the gemm source; no in-place aliasing)
            crd::containers::Array<T> tmp(alloc);
            if (!tmp.try_reserve(r * rest))
            {
                return TensorStatus::AllocFailed;
            }
            tmp.resize(r * rest);
            {
                const crd::hesap::dense::MatrixView<const T, dn::Layout::RowMajor> uv{
                    f.u.data(), static_cast<crd::usize>(m), static_cast<crd::usize>(r),
                    static_cast<crd::usize>(f.u.cols())};
                const crd::hesap::dense::MatrixView<const T, dn::Layout::RowMajor> cv{
                    carry.data(), static_cast<crd::usize>(m), static_cast<crd::usize>(rest),
                    static_cast<crd::usize>(rest)};
                crd::hesap::dense::MatrixView<T, dn::Layout::RowMajor> ov =
                    ttdetail::mview_mut(tmp.data(), r, rest);
                dn::gemm<T, dn::Layout::RowMajor>(T(1), uv, cv, T(0), ov, dn::Trans::Transpose,
                                                  dn::Trans::None, alloc);
            }
            for (crd::u64 i = 0; i < r * rest; ++i)
            {
                carry.data()[i] = tmp.data()[i];
            }
        }
        else
        {
            dn::Matrix<T> mat(alloc, static_cast<crd::usize>(m), static_cast<crd::usize>(rest));
            const T* src = carry.data();
            for (crd::u64 i = 0; i < m; ++i)
            {
                for (crd::u64 j = 0; j < rest; ++j)
                {
                    mat.at(static_cast<crd::usize>(i), static_cast<crd::usize>(j)) = src[i * rest + j];
                }
            }
            dn::SVD<T> f = dn::svd<T>(alloc, mat);
            const crd::u64 minmn = static_cast<crd::u64>(f.s.size());
            r = ttdetail::rank_chop(f.s.data(), minmn, delta, max_rank);
            // core k = U(:, :r) reshaped (r_prev, n_k, r)
            if (!corebuf.try_reserve(old + m * r))
            {
                return TensorStatus::AllocFailed;
            }
            corebuf.resize(old + m * r);
            for (crd::u64 i = 0; i < m; ++i)
            {
                for (crd::u64 j = 0; j < r; ++j)
                {
                    corebuf.data()[old + i * r + j] =
                        f.u.at(static_cast<crd::usize>(i), static_cast<crd::usize>(j));
                }
            }
            // C := diag(s_r) * V(:, :r)^T  (r x rest)
            T* dst = carry.data();
            for (crd::u64 i = 0; i < r; ++i)
            {
                const T si = f.s.data()[i];
                for (crd::u64 j = 0; j < rest; ++j)
                {
                    dst[i * rest + j] = si * f.v.at(static_cast<crd::usize>(j), static_cast<crd::usize>(i));
                }
            }
        }
        core_off[k + 1U] = old + m * r;
        ranks[k + 1U] = r;
        r_prev = r;
        if (k + 2U <= d - 1U)
        {
            rest /= a.shape(k + 1U);
        }
    }
    // last core = C reshaped (r_prev, n_{d-1}, 1); rest == n_{d-1} here
    {
        const crd::u64 old = static_cast<crd::u64>(corebuf.size());
        const crd::u64 cs = r_prev * rest;
        if (!corebuf.try_reserve(old + cs))
        {
            return TensorStatus::AllocFailed;
        }
        corebuf.resize(old + cs);
        for (crd::u64 i = 0; i < cs; ++i)
        {
            corebuf.data()[old + i] = carry.data()[i];
        }
        core_off[d] = old + cs;
        ranks[d] = 1U;
    }
    const TensorStatus st = out.init(a.shape(), {ranks, static_cast<crd::usize>(d) + 1U});
    if (st != TensorStatus::Ok)
    {
        return st;
    }
    for (crd::u32 k = 0; k < d; ++k)
    {
        const T* src = corebuf.data() + core_off[k];
        T* dst = out.core(k);
        const crd::u64 cs = out.core_size(k);
        for (crd::u64 i = 0; i < cs; ++i)
        {
            dst[i] = src[i];
        }
    }
    return TensorStatus::Ok;
}

// -----------------------------------------------------------------------
// tt_round — re-compress a TT to relative tolerance `tol` (+ optional rank
// cap). Right-to-left QR orthogonalization, then left-to-right SVD
// truncation with delta = tol*||A||_F/sqrt(d-1) (Oseledets 2011 Alg. 2 —
// the oracle's np_tt_round). Error contract (gated):
// ||A - round(A)||_F <= tol * ||A||_F. In place on `tt`.
// -----------------------------------------------------------------------
template <typename T>
[[nodiscard]] TensorStatus tt_round(crd::memory::IAllocator* alloc, TtTensor<T>& tt, T tol,
                                    crd::u64 max_rank = 0) noexcept
{
    namespace dn = crd::hesap::dense;
    if (alloc == nullptr || tt.dims() == 0U || tol < T(0))
    {
        return TensorStatus::BadInput;
    }
    const crd::u32 d = tt.dims();
    if (d == 1U)
    {
        return TensorStatus::Ok; // single core: nothing to compress
    }
    // work copy (both sweeps only ever SHRINK core sizes => fixed offsets)
    crd::u64 off[kMaxRank + 1U];
    crd::u64 rk[kMaxRank + 1U];
    crd::u64 total = 0;
    for (crd::u32 k = 0; k <= d; ++k)
    {
        rk[k] = tt.rank(k);
    }
    for (crd::u32 k = 0; k < d; ++k)
    {
        off[k] = total;
        total += tt.core_size(k);
    }
    off[d] = total;
    crd::containers::Array<T> work(alloc);
    if (!work.try_reserve(total))
    {
        return TensorStatus::AllocFailed;
    }
    work.resize(total);
    for (crd::u32 k = 0; k < d; ++k)
    {
        const T* src = tt.core(k);
        T* dst = work.data() + off[k];
        for (crd::u64 i = 0; i < tt.core_size(k); ++i)
        {
            dst[i] = src[i];
        }
    }
    // scratch: transposed core / thin Q / R^T / gemm result / apply_q column
    crd::containers::Array<T> scratch(alloc);
    // ---- right-to-left QR orthogonalization ------------------------------
    for (crd::u32 k = d - 1U; k >= 1U; --k)
    {
        const crd::u64 rl = rk[k];
        const crd::u64 ncols = tt.shape(k) * rk[k + 1U];
        const crd::u64 kk = rl < ncols ? rl : ncols;
        dn::QR<T> qr(alloc, static_cast<crd::usize>(ncols), static_cast<crd::usize>(rl));
        {
            const T* m = work.data() + off[k]; // (rl x ncols) row-major
            dn::Matrix<T>& p = qr.packed();
            for (crd::u64 i = 0; i < ncols; ++i)
            {
                for (crd::u64 j = 0; j < rl; ++j)
                {
                    p.at(static_cast<crd::usize>(i), static_cast<crd::usize>(j)) = m[j * ncols + i];
                }
            }
        }
        dn::factor_qr(qr);
        const crd::u64 need = ncols * kk /*Q*/ + rl * kk /*R^T*/ + ncols /*col*/;
        if (!scratch.try_reserve(need))
        {
            return TensorStatus::AllocFailed;
        }
        scratch.resize(need);
        T* q = scratch.data();
        T* rt = q + ncols * kk;
        T* colbuf = rt + rl * kk;
        ttdetail::form_thin_q(qr, q, ncols, kk, colbuf);
        for (crd::u64 i = 0; i < rl; ++i) // R^T (rl x kk) from the packed upper
        {
            for (crd::u64 j = 0; j < kk; ++j)
            {
                rt[i * kk + j] =
                    j <= i ? qr.packed().at(static_cast<crd::usize>(j), static_cast<crd::usize>(i)) : T(0);
            }
        }
        // core k := Q^T (kk x ncols); core k-1 := (prev unfold) @ R^T
        {
            T* m = work.data() + off[k];
            for (crd::u64 i = 0; i < kk; ++i)
            {
                for (crd::u64 j = 0; j < ncols; ++j)
                {
                    m[i * ncols + j] = q[j * kk + i];
                }
            }
        }
        {
            const crd::u64 prows = rk[k - 1U] * tt.shape(k - 1U);
            crd::containers::Array<T> tmp(alloc);
            if (!tmp.try_reserve(prows * kk))
            {
                return TensorStatus::AllocFailed;
            }
            tmp.resize(prows * kk);
            ttdetail::gemm_rm(static_cast<const T*>(work.data() + off[k - 1U]),
                              static_cast<const T*>(rt), tmp.data(), prows, rl, kk, alloc);
            T* dst = work.data() + off[k - 1U];
            for (crd::u64 i = 0; i < prows * kk; ++i)
            {
                dst[i] = tmp.data()[i];
            }
        }
        rk[k] = kk;
    }
    // ---- delta from the orthogonalized norm (= ||first core||_F) ---------
    const T nrm = ttdetail::fro_norm(work.data() + off[0], rk[0] * tt.shape(0) * rk[1]);
    const T delta = tol * nrm / std::sqrt(static_cast<T>(d - 1U));
    // ---- left-to-right SVD truncation ------------------------------------
    for (crd::u32 k = 0; k < d - 1U; ++k)
    {
        const crd::u64 m = rk[k] * tt.shape(k);
        const crd::u64 rr = rk[k + 1U];
        dn::Matrix<T> mat(alloc, static_cast<crd::usize>(m), static_cast<crd::usize>(rr));
        {
            const T* src = work.data() + off[k];
            for (crd::u64 i = 0; i < m; ++i)
            {
                for (crd::u64 j = 0; j < rr; ++j)
                {
                    mat.at(static_cast<crd::usize>(i), static_cast<crd::usize>(j)) = src[i * rr + j];
                }
            }
        }
        dn::SVD<T> f = dn::svd<T>(alloc, mat);
        const crd::u64 minmn = static_cast<crd::u64>(f.s.size());
        const crd::u64 r = ttdetail::rank_chop(f.s.data(), minmn, delta, max_rank);
        {
            T* dst = work.data() + off[k]; // core k := U(:, :r)
            for (crd::u64 i = 0; i < m; ++i)
            {
                for (crd::u64 j = 0; j < r; ++j)
                {
                    dst[i * r + j] = f.u.at(static_cast<crd::usize>(i), static_cast<crd::usize>(j));
                }
            }
        }
        {
            // carry = diag(s_r) V_r^T (r x rr); core k+1 := carry @ (unfold rr x n*r2)
            const crd::u64 ncols2 = tt.shape(k + 1U) * rk[k + 2U]; // k <= d-2 => k+2 <= d
            crd::containers::Array<T> cbuf(alloc);
            if (!cbuf.try_reserve(r * rr + r * ncols2))
            {
                return TensorStatus::AllocFailed;
            }
            cbuf.resize(r * rr + r * ncols2);
            T* carry = cbuf.data();
            T* prod = cbuf.data() + r * rr;
            for (crd::u64 i = 0; i < r; ++i)
            {
                const T si = f.s.data()[i];
                for (crd::u64 j = 0; j < rr; ++j)
                {
                    carry[i * rr + j] = si * f.v.at(static_cast<crd::usize>(j), static_cast<crd::usize>(i));
                }
            }
            ttdetail::gemm_rm(static_cast<const T*>(carry),
                              static_cast<const T*>(work.data() + off[k + 1U]), prod, r, rr, ncols2, alloc);
            T* dst = work.data() + off[k + 1U];
            for (crd::u64 i = 0; i < r * ncols2; ++i)
            {
                dst[i] = prod[i];
            }
        }
        rk[k + 1U] = r;
    }
    // ---- copy out ---------------------------------------------------------
    TtTensor<T> outp(alloc);
    const TensorStatus st = outp.init(tt.shape(), {rk, static_cast<crd::usize>(d) + 1U});
    if (st != TensorStatus::Ok)
    {
        return st;
    }
    for (crd::u32 k = 0; k < d; ++k)
    {
        const T* src = work.data() + off[k];
        T* dst = outp.core(k);
        for (crd::u64 i = 0; i < outp.core_size(k); ++i)
        {
            dst[i] = src[i];
        }
    }
    tt = static_cast<TtTensor<T>&&>(outp);
    return TensorStatus::Ok;
}

// -----------------------------------------------------------------------
// tt_add — C = A + B in TT format (block concatenation; structural ranks
// rC = rA + rB on interior edges). Round afterwards to re-compress.
// -----------------------------------------------------------------------
template <typename T>
[[nodiscard]] TensorStatus tt_add(crd::memory::IAllocator* alloc, const TtTensor<T>& a, const TtTensor<T>& b,
                                  TtTensor<T>& out) noexcept
{
    if (alloc == nullptr || a.dims() == 0U || a.dims() != b.dims())
    {
        return TensorStatus::BadInput;
    }
    const crd::u32 d = a.dims();
    for (crd::u32 k = 0; k < d; ++k)
    {
        if (a.shape(k) != b.shape(k))
        {
            return TensorStatus::ShapeMismatch;
        }
    }
    crd::u64 rk[kMaxRank + 1U];
    rk[0] = 1U;
    rk[d] = 1U;
    for (crd::u32 k = 1; k < d; ++k)
    {
        rk[k] = a.rank(k) + b.rank(k);
    }
    const TensorStatus st = out.init(a.shape(), {rk, static_cast<crd::usize>(d) + 1U});
    if (st != TensorStatus::Ok)
    {
        return st;
    }
    if (d == 1U)
    {
        for (crd::u64 i = 0; i < a.shape(0); ++i)
        {
            out.core(0)[i] = a.core(0)[i] + b.core(0)[i];
        }
        return TensorStatus::Ok;
    }
    for (crd::u32 k = 0; k < d; ++k)
    {
        const crd::u64 al = a.rank(k);
        const crd::u64 ar = a.rank(k + 1U);
        const crd::u64 bl = b.rank(k);
        const crd::u64 br = b.rank(k + 1U);
        const crd::u64 cl = k == 0U ? 1U : al + bl;
        const crd::u64 cr = k == d - 1U ? 1U : ar + br;
        const crd::u64 n = a.shape(k);
        T* dst = out.core(k);
        for (crd::u64 i = 0; i < cl * n * cr; ++i)
        {
            dst[i] = T(0);
        }
        const T* pa = a.core(k);
        const T* pb = b.core(k);
        for (crd::u64 x = 0; x < al; ++x) // A block at [0:al, :, 0:ar]
        {
            for (crd::u64 i = 0; i < n; ++i)
            {
                for (crd::u64 y = 0; y < ar; ++y)
                {
                    dst[(x * n + i) * cr + y] = pa[(x * n + i) * ar + y];
                }
            }
        }
        const crd::u64 xo = k == 0U ? 0U : al; // B block at [al:, :, ar:] (boundary-collapsed)
        const crd::u64 yo = k == d - 1U ? 0U : ar;
        for (crd::u64 x = 0; x < bl; ++x)
        {
            for (crd::u64 i = 0; i < n; ++i)
            {
                for (crd::u64 y = 0; y < br; ++y)
                {
                    dst[((xo + x) * n + i) * cr + (yo + y)] = pb[(x * n + i) * br + y];
                }
            }
        }
    }
    return TensorStatus::Ok;
}

// -----------------------------------------------------------------------
// tt_hadamard — C = A .* B in TT format (slice-wise Kronecker product;
// structural ranks rC = rA * rB). Round afterwards to re-compress.
// -----------------------------------------------------------------------
template <typename T>
[[nodiscard]] TensorStatus tt_hadamard(crd::memory::IAllocator* alloc, const TtTensor<T>& a,
                                       const TtTensor<T>& b, TtTensor<T>& out) noexcept
{
    if (alloc == nullptr || a.dims() == 0U || a.dims() != b.dims())
    {
        return TensorStatus::BadInput;
    }
    const crd::u32 d = a.dims();
    for (crd::u32 k = 0; k < d; ++k)
    {
        if (a.shape(k) != b.shape(k))
        {
            return TensorStatus::ShapeMismatch;
        }
    }
    crd::u64 rk[kMaxRank + 1U];
    for (crd::u32 k = 0; k <= d; ++k)
    {
        rk[k] = a.rank(k) * b.rank(k);
    }
    const TensorStatus st = out.init(a.shape(), {rk, static_cast<crd::usize>(d) + 1U});
    if (st != TensorStatus::Ok)
    {
        return st;
    }
    for (crd::u32 k = 0; k < d; ++k)
    {
        const crd::u64 al = a.rank(k);
        const crd::u64 ar = a.rank(k + 1U);
        const crd::u64 bl = b.rank(k);
        const crd::u64 br = b.rank(k + 1U);
        const crd::u64 n = a.shape(k);
        const T* pa = a.core(k);
        const T* pb = b.core(k);
        T* dst = out.core(k);
        for (crd::u64 i = 0; i < n; ++i) // per-slice Kronecker
        {
            for (crd::u64 x1 = 0; x1 < al; ++x1)
            {
                for (crd::u64 x2 = 0; x2 < bl; ++x2)
                {
                    const crd::u64 row = x1 * bl + x2;
                    for (crd::u64 y1 = 0; y1 < ar; ++y1)
                    {
                        const T av = pa[(x1 * n + i) * ar + y1];
                        for (crd::u64 y2 = 0; y2 < br; ++y2)
                        {
                            dst[(row * n + i) * (ar * br) + y1 * br + y2] =
                                av * pb[(x2 * n + i) * br + y2];
                        }
                    }
                }
            }
        }
    }
    return TensorStatus::Ok;
}

// -----------------------------------------------------------------------
// tt_dot — inner product <A, B> = sum over all indices of A .* B.
// Two gemms per core: O(d * n * r^3). tt_norm = sqrt(<A, A>).
// -----------------------------------------------------------------------
template <typename T>
[[nodiscard]] TensorStatus tt_dot(crd::memory::IAllocator* alloc, const TtTensor<T>& a, const TtTensor<T>& b,
                                  T& out) noexcept
{
    if (alloc == nullptr || a.dims() == 0U || a.dims() != b.dims())
    {
        return TensorStatus::BadInput;
    }
    const crd::u32 d = a.dims();
    crd::u64 mra = 1;
    crd::u64 mrb = 1;
    for (crd::u32 k = 0; k < d; ++k)
    {
        if (a.shape(k) != b.shape(k))
        {
            return TensorStatus::ShapeMismatch;
        }
        if (a.rank(k) > mra)
        {
            mra = a.rank(k);
        }
        if (b.rank(k) > mrb)
        {
            mrb = b.rank(k);
        }
    }
    crd::u64 maxn = 0;
    for (crd::u32 k = 0; k < d; ++k)
    {
        if (a.shape(k) > maxn)
        {
            maxn = a.shape(k);
        }
    }
    crd::containers::Array<T> buf(alloc);
    const crd::u64 vcap = mra * mrb;
    const crd::u64 t1cap = mrb * maxn * mra;
    if (!buf.try_reserve(vcap * 2U + t1cap))
    {
        return TensorStatus::AllocFailed;
    }
    buf.resize(vcap * 2U + t1cap);
    T* v = buf.data();          // (ra_l x rb_l)
    T* vn = buf.data() + vcap;  // (ra_r x rb_r)
    T* t1 = buf.data() + vcap * 2U;
    v[0] = T(1);
    for (crd::u32 k = 0; k < d; ++k)
    {
        const crd::u64 ral = a.rank(k);
        const crd::u64 rar = a.rank(k + 1U);
        const crd::u64 rbl = b.rank(k);
        const crd::u64 rbr = b.rank(k + 1U);
        const crd::u64 n = a.shape(k);
        // t1 = v^T (rbl x ral) @ A_k unfold (ral x n*rar)  -> (rbl x n*rar)
        {
            crd::hesap::dense::MatrixView<T, crd::hesap::dense::Layout::RowMajor> cv =
                ttdetail::mview_mut(t1, rbl, n * rar);
            crd::hesap::dense::gemm<T, crd::hesap::dense::Layout::RowMajor>(
                T(1), ttdetail::mview(v, ral, rbl), ttdetail::mview(a.core(k), ral, n * rar), T(0), cv,
                crd::hesap::dense::Trans::Transpose, crd::hesap::dense::Trans::None, alloc);
        }
        // vn = t1 viewed (rbl*n x rar)^T @ B_k unfold (rbl*n x rbr) -> (rar x rbr)
        {
            crd::hesap::dense::MatrixView<T, crd::hesap::dense::Layout::RowMajor> cv =
                ttdetail::mview_mut(vn, rar, rbr);
            crd::hesap::dense::gemm<T, crd::hesap::dense::Layout::RowMajor>(
                T(1), ttdetail::mview(t1, rbl * n, rar), ttdetail::mview(b.core(k), rbl * n, rbr), T(0), cv,
                crd::hesap::dense::Trans::Transpose, crd::hesap::dense::Trans::None, alloc);
        }
        T* tmp = v;
        v = vn;
        vn = tmp;
    }
    out = v[0];
    return TensorStatus::Ok;
}

template <typename T>
[[nodiscard]] TensorStatus tt_norm(crd::memory::IAllocator* alloc, const TtTensor<T>& a, T& out) noexcept
{
    T dot = T(0);
    const TensorStatus st = tt_dot(alloc, a, a, dot);
    if (st != TensorStatus::Ok)
    {
        return st;
    }
    out = dot > T(0) ? std::sqrt(dot) : T(0);
    return TensorStatus::Ok;
}

// -----------------------------------------------------------------------
// tt_contract — materialize the TT into a dense (row-major) Tensor.
// One gemm per core: P (M x r_k) @ unfold_k (r_k x n_k*r_{k+1}).
// -----------------------------------------------------------------------
template <typename T>
[[nodiscard]] TensorStatus tt_contract(crd::memory::IAllocator* alloc, const TtTensor<T>& a,
                                       Tensor<T>& out) noexcept
{
    if (alloc == nullptr || a.dims() == 0U)
    {
        return TensorStatus::BadInput;
    }
    const crd::u32 d = a.dims();
    TensorStatus st = out.resize(a.shape());
    if (st != TensorStatus::Ok)
    {
        return st;
    }
    // ping-pong buffers sized to the largest intermediate (prefix M * r)
    crd::u64 maxint = a.shape(0) * a.rank(1);
    {
        crd::u64 m = a.shape(0);
        for (crd::u32 k = 1; k < d; ++k)
        {
            m *= a.shape(k);
            const crd::u64 sz = m * a.rank(k + 1U);
            if (sz > maxint)
            {
                maxint = sz;
            }
        }
    }
    crd::containers::Array<T> buf(alloc);
    if (!buf.try_reserve(maxint * 2U))
    {
        return TensorStatus::AllocFailed;
    }
    buf.resize(maxint * 2U);
    T* cur = buf.data();
    T* nxt = buf.data() + maxint;
    crd::u64 m = a.shape(0);
    crd::u64 r = a.rank(1);
    for (crd::u64 i = 0; i < m * r; ++i)
    {
        cur[i] = a.core(0)[i];
    }
    for (crd::u32 k = 1; k < d; ++k)
    {
        const crd::u64 n = a.shape(k);
        const crd::u64 rn = a.rank(k + 1U);
        ttdetail::gemm_rm(static_cast<const T*>(cur), a.core(k), nxt, m, r, n * rn, alloc);
        m *= n;
        r = rn;
        T* tmp = cur;
        cur = nxt;
        nxt = tmp;
    }
    for (crd::u64 i = 0; i < m; ++i)
    {
        out.data()[i] = cur[i];
    }
    return TensorStatus::Ok;
}

// -----------------------------------------------------------------------
// tt_eval — evaluate a single element. ALLOCATION-FREE: caller workspace of
// size >= tt_eval_workspace(tt) == 2 * max_rank(tt) (checked by assert; the
// formula is part of the contract). Left-to-right row-vector chain:
// v <- v @ G_k[:, i_k, :]. noexcept, no allocator anywhere on the path.
// -----------------------------------------------------------------------
template <typename T> [[nodiscard]] crd::u64 tt_eval_workspace(const TtTensor<T>& tt) noexcept
{
    return 2U * tt.max_rank();
}

template <typename T>
[[nodiscard]] T tt_eval(const TtTensor<T>& tt, crd::containers::ConstSpan<crd::u64> idx,
                        crd::containers::Span<T> work) noexcept
{
    const crd::u32 d = tt.dims();
    CRD_ASSERT_MSG(idx.size() == d, "tt_eval: index rank mismatch");
    CRD_ASSERT_MSG(work.size() >= tt_eval_workspace(tt), "tt_eval: workspace too small (2*max_rank)");
    const crd::u64 mr = tt.max_rank();
    T* v = work.data();
    T* w = work.data() + mr;
    {
        CRD_ASSERT_MSG(idx[0] < tt.shape(0), "tt_eval: index out of range");
        const crd::u64 r1 = tt.rank(1);
        const T* g = tt.core(0) + idx[0] * r1; // (1, n0, r1): row i0
        for (crd::u64 j = 0; j < r1; ++j)
        {
            v[j] = g[j];
        }
    }
    for (crd::u32 k = 1; k < d; ++k)
    {
        CRD_ASSERT_MSG(idx[k] < tt.shape(k), "tt_eval: index out of range");
        const crd::u64 rl = tt.rank(k);
        const crd::u64 rr = tt.rank(k + 1U);
        const crd::u64 n = tt.shape(k);
        const T* g = tt.core(k) + idx[k] * rr; // slice row a: g + a*n*rr
        for (crd::u64 j = 0; j < rr; ++j)
        {
            T s = T(0);
            for (crd::u64 x = 0; x < rl; ++x)
            {
                s = std::fma(v[x], g[x * n * rr + j], s);
            }
            w[j] = s;
        }
        T* tmp = v;
        v = w;
        w = tmp;
    }
    return v[0];
}

// Batched span evaluator: idx_flat = npts * dims() indices (row-major
// points); out receives npts values. ALLOCATION-FREE (same workspace,
// reused across points). Returns BadInput on size mismatches.
template <typename T>
[[nodiscard]] TensorStatus tt_eval_many(const TtTensor<T>& tt, crd::containers::ConstSpan<crd::u64> idx_flat,
                                        crd::containers::Span<T> out,
                                        crd::containers::Span<T> work) noexcept
{
    const crd::u32 d = tt.dims();
    if (d == 0U || idx_flat.size() != out.size() * d || work.size() < tt_eval_workspace(tt))
    {
        return TensorStatus::BadInput;
    }
    const crd::u64 npts = out.size();
    for (crd::u64 p = 0; p < npts; ++p)
    {
        out[p] = tt_eval(tt, {idx_flat.data() + p * d, d}, work);
    }
    return TensorStatus::Ok;
}

// -----------------------------------------------------------------------
// tt_eval_lerp — multilinear-interpolated point evaluation: cell base index
// i0[k] (i0[k]+1 < shape(k) required unless w[k] == 0) + fractional weights
// w[k] in [0,1]. EQUALS multilinear interpolation of the dense grid (the
// interpolation functional is a tensor product of per-dim linear maps, which
// factors through the cores) — gated. ALLOCATION-FREE, same workspace
// formula. The v13-interp LUT hot path: d fused slice-blend matvecs.
// -----------------------------------------------------------------------
template <typename T>
[[nodiscard]] T tt_eval_lerp(const TtTensor<T>& tt, crd::containers::ConstSpan<crd::u64> i0,
                             crd::containers::ConstSpan<T> w, crd::containers::Span<T> work) noexcept
{
    const crd::u32 d = tt.dims();
    CRD_ASSERT_MSG(i0.size() == d && w.size() == d, "tt_eval_lerp: index/weight rank mismatch");
    CRD_ASSERT_MSG(work.size() >= tt_eval_workspace(tt), "tt_eval_lerp: workspace too small (2*max_rank)");
    const crd::u64 mr = tt.max_rank();
    T* v = work.data();
    T* wk = work.data() + mr;
    {
        const crd::u64 r1 = tt.rank(1);
        const crd::u64 i = i0[0];
        const T t = w[0];
        CRD_ASSERT_MSG(i < tt.shape(0) && (t == T(0) || i + 1U < tt.shape(0)),
                       "tt_eval_lerp: cell out of range");
        const T* g0 = tt.core(0) + i * r1;
        const T* g1 = t == T(0) ? g0 : g0 + r1;
        for (crd::u64 j = 0; j < r1; ++j)
        {
            v[j] = std::fma(t, g1[j] - g0[j], g0[j]);
        }
    }
    for (crd::u32 k = 1; k < d; ++k)
    {
        const crd::u64 rl = tt.rank(k);
        const crd::u64 rr = tt.rank(k + 1U);
        const crd::u64 n = tt.shape(k);
        const crd::u64 i = i0[k];
        const T t = w[k];
        CRD_ASSERT_MSG(i < n && (t == T(0) || i + 1U < n), "tt_eval_lerp: cell out of range");
        const T* g0 = tt.core(k) + i * rr;
        const T* g1 = t == T(0) ? g0 : g0 + rr;
        for (crd::u64 j = 0; j < rr; ++j)
        {
            T s = T(0);
            for (crd::u64 x = 0; x < rl; ++x)
            {
                const T a0 = g0[x * n * rr + j];
                const T blended = std::fma(t, g1[x * n * rr + j] - a0, a0);
                s = std::fma(v[x], blended, s);
            }
            wk[j] = s;
        }
        T* tmp = v;
        v = wk;
        wk = tmp;
    }
    return v[0];
}

