// row-major MatrixView helpers over raw buffers (the batched.hpp pattern)
template <typename T>
[[nodiscard]] inline crd::hesap::dense::MatrixView<const T, crd::hesap::dense::Layout::RowMajor>
mview(const T* p, crd::u64 rows, crd::u64 cols) noexcept
{
    return {p, static_cast<crd::usize>(rows), static_cast<crd::usize>(cols), static_cast<crd::usize>(cols)};
}

template <typename T>
[[nodiscard]] inline crd::hesap::dense::MatrixView<T, crd::hesap::dense::Layout::RowMajor>
mview_mut(T* p, crd::u64 rows, crd::u64 cols) noexcept
{
    return {p, static_cast<crd::usize>(rows), static_cast<crd::usize>(cols), static_cast<crd::usize>(cols)};
}

// C = A(rows_a x k) @ B(k x cols_b), row-major tight, via hesap-dense gemm.
template <typename T>
inline void gemm_rm(const T* a, const T* b, T* c, crd::u64 rows, crd::u64 k, crd::u64 cols,
                    crd::memory::IAllocator* scratch) noexcept
{
    crd::hesap::dense::MatrixView<T, crd::hesap::dense::Layout::RowMajor> cv = mview_mut(c, rows, cols);
    crd::hesap::dense::gemm<T, crd::hesap::dense::Layout::RowMajor>(
        T(1), mview(a, rows, k), mview(b, k, cols), T(0), cv, crd::hesap::dense::Trans::None,
        crd::hesap::dense::Trans::None, scratch);
}

// Frobenius norm of a raw buffer (sequential order — deterministic).
template <typename T> [[nodiscard]] inline T fro_norm(const T* p, crd::u64 n) noexcept
{
    T s = T(0);
    for (crd::u64 i = 0; i < n; ++i)
    {
        s = std::fma(p[i], p[i], s);
    }
    return std::sqrt(s);
}

// Truncation rank: smallest r >= 1 with sum_{i>=r} s_i^2 <= delta^2, capped.
// EXACT mirror of the oracle's rank_chop (scripts/v14k_tt_oracle.py).
template <typename T>
[[nodiscard]] inline crd::u64 rank_chop(const T* s, crd::u64 count, T delta, crd::u64 rmax) noexcept
{
    crd::u64 r = count;
    T tail = T(0);
    for (crd::u64 i = count; i-- > 1U;)
    {
        tail = std::fma(s[i], s[i], tail);
        if (tail > delta * delta)
        {
            break;
        }
        r = i;
    }
    if (r < 1U)
    {
        r = 1U;
    }
    if (rmax != 0U && r > rmax)
    {
        r = rmax;
    }
    if (r > count)
    {
        r = count;
    }
    return r;
}

// Thin Q formation from a factored Householder QR: Q(:, c) = Q * e_c.
// HOME-> hesap-dense: an orgqr-style explicit thin-Q builder belongs in
// qr.hpp; until it ships we form Q by applying the reflectors to identity
// columns (O(m*k^2), same complexity as the factorization itself).
template <typename T>
inline void form_thin_q(const crd::hesap::dense::QR<T, crd::hesap::dense::Layout::RowMajor>& qr, T* q,
                        crd::u64 m, crd::u64 kk, T* colbuf) noexcept
{
    for (crd::u64 c = 0; c < kk; ++c)
    {
        for (crd::u64 i = 0; i < m; ++i)
        {
            colbuf[i] = i == c ? T(1) : T(0);
        }
        crd::hesap::dense::apply_q(qr, crd::containers::Span<T>{colbuf, static_cast<crd::usize>(m)});
        for (crd::u64 i = 0; i < m; ++i)
        {
            q[i * kk + c] = colbuf[i];
        }
    }
}

