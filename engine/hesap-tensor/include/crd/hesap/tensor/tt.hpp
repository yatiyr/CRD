// TT-cross scratch geometry: index-set offsets for the flat lset/rset pools
// (fixed ranks => fixed sizes; buffers are pre-sized ONCE before any span is
// taken — the reserve-before-spans rule).
struct CrossLayout
{
    crd::u64 rs[kMaxRank + 1U];      // clamped TT ranks
    crd::u64 lset_off[kMaxRank + 1U]; // lsets[j]: rs[j] rows of length j
    crd::u64 rset_off[kMaxRank + 1U]; // rsets[j]: rs[j+1] rows of length d-1-j
    crd::u64 core_off[kMaxRank + 1U]; // cores[j]: rs[j]*n_j*rs[j+1]
    crd::u64 lset_total = 0;
    crd::u64 rset_total = 0;
    crd::u64 core_total = 0;
    crd::u64 max_fiber = 0;          // max_j rs[j]*n_j*rs[j+1]
    crd::u64 max_rank = 0;
};

inline void cross_layout(crd::containers::ConstSpan<crd::u64> shape, crd::u64 max_rank,
                         CrossLayout& lay) noexcept
{
    const crd::u32 d = static_cast<crd::u32>(shape.size());
    lay.rs[0] = 1U;
    lay.rs[d] = 1U;
    for (crd::u32 k = 1; k < d; ++k)
    {
        lay.rs[k] = max_rank;
    }
    for (crd::u32 k = 1; k < d; ++k) // clamp L2R then R2L (the tntorch rule)
    {
        const crd::u64 cap = lay.rs[k - 1U] * shape[k - 1U];
        if (lay.rs[k] > cap)
        {
            lay.rs[k] = cap;
        }
    }
    for (crd::u32 k = d - 1U; k >= 1U; --k)
    {
        const crd::u64 cap = shape[k] * lay.rs[k + 1U];
        if (lay.rs[k] > cap)
        {
            lay.rs[k] = cap;
        }
    }
    lay.lset_total = 0;
    lay.rset_total = 0;
    lay.core_total = 0;
    lay.max_fiber = 0;
    lay.max_rank = 1;
    for (crd::u32 j = 0; j < d; ++j)
    {
        lay.lset_off[j] = lay.lset_total;
        lay.lset_total += lay.rs[j] * j;
        lay.rset_off[j] = lay.rset_total;
        lay.rset_total += lay.rs[j + 1U] * (d - 1U - j);
        lay.core_off[j] = lay.core_total;
        const crd::u64 fib = lay.rs[j] * shape[j] * lay.rs[j + 1U];
        lay.core_total += fib;
        if (fib > lay.max_fiber)
        {
            lay.max_fiber = fib;
        }
        if (lay.rs[j + 1U] > lay.max_rank)
        {
            lay.max_rank = lay.rs[j + 1U];
        }
    }
    lay.lset_off[d] = lay.lset_total;
    lay.rset_off[d] = lay.rset_total;
    lay.core_off[d] = lay.core_total;
}

