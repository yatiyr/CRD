#!/usr/bin/env python3
"""Generate the comply owner's rule generations from the COMPLY.0 legal register.

cmake/legal-register.json is the authored source of every legal and platform obligation
(docs/design/registers.md#rule-generations). Products never read it: this generator writes, for every jurisdiction
holding a rule (an `obligation` or `user-action` entry that is `planned` or `implemented`), one `cerid-rules/1`
document, assets/comply/<code>.rules.toml, which `crd::comply::RuleStore` decodes and swaps live. The register's
`rule_generations` records each jurisdiction's generation number, the day it was reviewed and the SHA-256 of its
file; scripts/check-registers.py fails a file that no longer matches its record, so changed rules reach products only
through a review.

  python scripts/gen-comply-rules.py                       # write every generation at its recorded number
  python scripts/gen-comply-rules.py --check               # byte-compare with the committed files; nonzero on drift
  python scripts/gen-comply-rules.py --review TR [--day D] # review TR's changed rules: next generation, day, digest

The crd-comply-rules-drift CTest runs --check; scripts/generated-sources.json records each file's bytes.
"""
import argparse
import datetime
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTER = 'cmake/legal-register.json'
GENERATOR = 'scripts/gen-comply-rules.py'
OUT_DIR = 'assets/comply'
SUFFIX = '.rules.toml'
FORMAT = 'cerid-rules/1'
RULE_KINDS = {'obligation', 'user-action'}
RULE_STATES = {'planned', 'implemented'}


class RuleError(Exception):
    pass


def file_name(code):
    return f'{OUT_DIR}/{code.lower()}{SUFFIX}'


def quote(text):
    """A TOML basic string: quotes, backslashes and control characters escaped, other text as UTF-8."""
    out = ['"']
    for char in text:
        if char in '"\\':
            out.append('\\' + char)
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            out.append(f'\\u{ord(char):04X}')
        else:
            out.append(char)
    return ''.join(out + ['"'])


def strings(values):
    return '[' + ', '.join(quote(value) for value in values) + ']'


def counsel_of(counsel):
    if counsel['reviewed']:
        return 'reviewed'
    return 'needed' if counsel['needed'] else 'none'


def rules_by_jurisdiction(register):
    """{code: [entry]} of the rule entries, in register order."""
    grouped = {}
    for entry in register['entries']:
        if entry['kind'] in RULE_KINDS and entry['state'] in RULE_STATES:
            grouped.setdefault(entry['instrument']['jurisdiction'], []).append(entry)
    return grouped


def render(code, generation, register, rules):
    scopes = {scope['id']: scope for scope in register['scopes']}
    named = []
    for rule in rules:
        for scope in rule['applies_to']:
            if scope not in scopes:
                raise RuleError(f'{rule["id"]} applies to the unknown scope {scope!r}')
            if scope not in named:
                named.append(scope)
    lines = [f'# Generated by {GENERATOR} from {REGISTER}; never edit by hand.',
             f'# A change is reviewed with: python {GENERATOR} --review {code}',
             f'format = {quote(FORMAT)}',
             f'jurisdiction = {quote(code)}',
             f'generation = {generation}',
             f'register = {quote(register["snapshot"]["date"])}']
    for scope_id in sorted(named, key=list(scopes).index):
        scope = scopes[scope_id]
        lines += ['', '[[scope]]', f'id = {quote(scope["id"])}', f'kind = {quote(scope["kind"])}',
                  f'state = {quote(scope["state"])}']
    for rule in rules:
        instrument, check = rule['instrument'], rule['check']
        lines += ['', '[[rule]]',
                  f'id = {quote(rule["id"])}',
                  f'kind = {quote(rule["kind"])}',
                  f'topic = {quote(rule["topic"])}',
                  f'state = {quote(rule["state"])}',
                  f'title = {quote(rule["title"])}',
                  f'instrument = {quote(instrument["name"])}',
                  f'article = {quote(instrument["article"])}',
                  f'primary = {quote(instrument["primary"])}',
                  f'read = {"true" if instrument["consolidated"] is not None else "false"}',
                  f'obligation = {quote(rule["obligation"])}',
                  f'applies_to = {strings(rule["applies_to"])}',
                  f'check = {quote(check["state"])}',
                  f'check_name = {quote(check["name"])}',
                  f'check_ref = {quote(check["ref"])}',
                  f'effective = {quote(rule["effective"] or "")}',
                  f'sunset = {quote(rule["sunset"] or "")}',
                  f'counsel = {quote(counsel_of(rule["counsel"]))}',
                  f'counsel_reviewed = {quote(rule["counsel"]["reviewed"] or "")}',
                  f'rows = {strings(rule["rows"])}']
    return '\n'.join(lines) + '\n'


def generation_of(register, code):
    record = (register.get('rule_generations') or {}).get(code)
    if not isinstance(record, dict) or not isinstance(record.get('generation'), int) or record['generation'] < 1:
        raise RuleError(f'{REGISTER}: rule_generations has no generation for {code}; review it with '
                        f'python {GENERATOR} --review {code}')
    return record['generation']


def outputs(register, generations=None):
    """{relative path: text} of every rule generation; `generations` overrides recorded numbers."""
    generations = generations or {}
    return {file_name(code): render(code, generations.get(code) or generation_of(register, code), register, rules)
            for code, rules in rules_by_jurisdiction(register).items()}


def digest(text):
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def review(root, register, code, day):
    """Record the review of `code`'s changed rules: the next generation, its day and its digest."""
    rules = rules_by_jurisdiction(register)
    if code not in rules:
        raise RuleError(f'{code} holds no rule (planned or implemented obligation or user action)')
    records = register.setdefault('rule_generations', {})
    record = records.get(code)
    if record is not None:
        current = render(code, record['generation'], register, rules[code])
        if digest(current) == record.get('sha256'):
            raise RuleError(f'{code}\'s rules are unchanged since generation {record["generation"]}; nothing to '
                            'review')
    number = record['generation'] + 1 if record is not None else 1
    text = render(code, number, register, rules[code])
    records[code] = {'generation': number, 'reviewed': day.isoformat(), 'sha256': digest(text)}
    register['rule_generations'] = {key: records[key] for key in sorted(records)}
    (root / REGISTER).write_bytes((json.dumps(register, ensure_ascii=False, indent=2) + '\n').encode('utf-8'))
    path = root / file_name(code)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode('utf-8'))
    return number


def main(argv=None):
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8')
    parser = argparse.ArgumentParser(description='Generate the comply rule generations from the legal register')
    parser.add_argument('--check', action='store_true', help='compare with the committed files instead of writing')
    parser.add_argument('--review', metavar='CODE', help='review one jurisdiction\'s changed rules')
    parser.add_argument('--day', help='the review day (YYYY-MM-DD; default the UTC date)')
    parser.add_argument('--root', default=str(ROOT), help='repository root (tests use a fixture)')
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    try:
        register = json.loads((root / REGISTER).read_text(encoding='utf-8'))
        if args.review:
            day = datetime.date.fromisoformat(args.day) if args.day else \
                datetime.datetime.now(datetime.timezone.utc).date()
            number = review(root, register, args.review, day)
            print(f'reviewed {args.review}: generation {number} on {day}, {file_name(args.review)}')
            return 0
        generated = outputs(register)
    except (RuleError, OSError, ValueError, KeyError) as error:
        print(f'FAIL: {error}')
        return 1
    drift = False
    out_dir = root / OUT_DIR
    present = {f'{OUT_DIR}/{path.name}' for path in out_dir.glob(f'*{SUFFIX}')} if out_dir.is_dir() else set()
    for relative, text in generated.items():
        path = root / relative
        if args.check:
            current = path.read_bytes() if path.exists() else None
            if current != text.encode('utf-8'):
                print(f'FAIL: {relative} differs from {GENERATOR}\'s output; run python {GENERATOR}')
                drift = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode('utf-8'))
            print(f'wrote {relative}')
    for stray in sorted(present - set(generated)):
        print(f'FAIL: {stray} is no jurisdiction\'s rule generation; delete it')
        drift = True
    if args.check and not drift:
        print(f'rule generations current: {len(generated)} jurisdiction(s)')
    return 1 if drift else 0


if __name__ == '__main__':
    sys.exit(main())
