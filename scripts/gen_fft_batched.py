"""gen_fft_batched.py — the rebuilt batched-codelet generator (2026-07-03 FFT campaign).

Rebuilds the lost build/gen_subfft_m3.py capability for the BATCHED SoA form: emits
codelet{N}_batched(const Complex<f64>*, Complex<f64>*, usize b) — split-radix DAG + CSE +
register-pressure schedule, on codelet_lanes.hpp's lanes over the batch axis, in the EXACT style of the surviving
generated kernels in hier_codelets.hpp (loads first, plain V(const) mul/add pairs, stores
last => in-place-safe by construction). Numerically validated vs numpy IN this script; the
engine's four-step oracle gates it end-to-end.

Run (WSL, the reference host): python3 scripts/gen_fft_batched.py [mode] [--check]. It writes
engine/numerics/hesap-fft/include/crd/hesap/fft/detail/batched_codelets_gen.hpp (the declarations) and the
codelet units engine/numerics/hesap-fft/kernels/fft_batched_codelets_<k>.cpp (fft_codegen_split.py); --check
compares instead and fails on any difference. Optional mode = scheduler: hybrid2 [tracked default] | hybrid |
greedy | belady — see SCHED_VARIANT.
"""
import cmath

import numpy as np

# ---- hash-consed DAG core (from gen_fft_crush.py, return typos fixed) ----
_TABLE = {}
_NODES = []


class Node:
    __slots__ = ("op", "a", "b", "c", "id")

    def __init__(self, op, a=None, b=None, c=None):
        self.op, self.a, self.b, self.c, self.id = op, a, b, c, len(_NODES)


def _node(op, a=None, b=None, c=None):
    key = (op, a.id if isinstance(a, Node) else a, b.id if isinstance(b, Node) else b, c)
    h = _TABLE.get(key)
    if h is not None:
        return h
    n = Node(op, a, b, c)
    _TABLE[key] = n
    _NODES.append(n)
    return n


def inp(i):
    return _node("input", i)


def add(a, b):
    return _node("add", a, b)


def sub(a, b):
    return _node("sub", a, b)


def cmul(a, w):
    if abs(w - 1) < 1e-15:
        return a
    if abs(w + 1) < 1e-15:
        return _node("neg", a)
    if abs(w - 1j) < 1e-15:
        return _node("muli", a)
    if abs(w + 1j) < 1e-15:
        return _node("mulni", a)
    return _node("cmul", a, None, (round(w.real, 17), round(w.imag, 17)))


def fft_dag(x):
    n = len(x)
    if n == 1:
        return [x[0]]
    if n == 2:
        return [add(x[0], x[1]), sub(x[0], x[1])]
    U = fft_dag(x[0::2])
    Z1 = fft_dag(x[1::4])
    Z3 = fft_dag(x[3::4])
    out = [None] * n
    q = n // 4
    for k in range(q):
        w1 = cmath.exp(-2j * cmath.pi * k / n)
        w3 = cmath.exp(-2j * cmath.pi * 3 * k / n)
        t1 = cmul(Z1[k], w1)
        t3 = cmul(Z3[k], w3)
        s = add(t1, t3)
        d = sub(t1, t3)
        di = _node("mulni", d)
        out[k] = add(U[k], s)
        out[k + n // 2] = sub(U[k], s)
        out[k + q] = add(U[k + q], di)
        out[k + 3 * q] = sub(U[k + q], di)
    return out


def evaluate(outputs, xvals):
    memo = {}

    def ev(node):
        if node.id in memo:
            return memo[node.id]
        op = node.op
        if op == "input":
            v = xvals[node.a]
        elif op == "add":
            v = ev(node.a) + ev(node.b)
        elif op == "sub":
            v = ev(node.a) - ev(node.b)
        elif op == "neg":
            v = -ev(node.a)
        elif op == "muli":
            v = 1j * ev(node.a)
        elif op == "mulni":
            v = -1j * ev(node.a)
        elif op == "cmul":
            v = complex(node.c[0], node.c[1]) * ev(node.a)
        else:
            raise ValueError(op)
        memo[node.id] = v
        return v

    return [ev(o) for o in outputs]


def _topo(outputs):
    order, seen = [], set()

    def visit(nd):
        if nd.id in seen:
            return
        seen.add(nd.id)
        for ch in (nd.a, nd.b):
            if isinstance(ch, Node):
                visit(ch)
        order.append(nd)

    for o in outputs:
        visit(o)
    return order


# Scheduler selection (A/B'd 2026-07-03): "greedy" = freed-count; "belady" adds a shortest-live-range
# tiebreak. Measured: belady wins broadly on the Vec8f/f32 kernels (+8..13% on the f32 sh band) and
# LOSES badly on the f64 deep-split kernels (256K −16%, 512K −68% — spill regime differs at 4 lanes).
# ⇒ the tracked default is "hybrid": f32 emitters schedule belady, f64 emitters greedy.
SCHED_VARIANT = "greedy"
# The longest SIMD body part and the codelet units (fft_codegen_split.py): an N=128 f64 body at the SSE2 level
# compiles in 16 s in parts of 150 lines, in more than 1,200 s and 14.7 GB whole, and the engine unit holding every
# codelet took 799 s and 4.9 GB at SSE2 (MSVC /O2, 2026-10-28).
SPLIT_BUDGET = 150
CODELET_UNITS = 7
HEADER = "engine/numerics/hesap-fft/include/crd/hesap/fft/detail/batched_codelets_gen.hpp"
UNIT = "engine/numerics/hesap-fft/kernels/fft_batched_codelets_{}.cpp"
UNIT_PRELUDE = """\
// GENERATED by scripts/gen_fft_batched.py — codelet unit {unit} of {units}: definitions of batched_codelets_gen.hpp.
#include <crd/hesap/fft/detail/batched_codelets_gen.hpp>
#include <crd/core/platform.hpp>
#include <crd/hesap/fft/detail/codelet_lanes.hpp>
"""


def schedule(outputs):
    nodes = _topo(outputs)
    ins_of = {}
    deps = {nd.id: [] for nd in nodes}
    for nd in nodes:
        ins = [c for c in (nd.a, nd.b) if isinstance(c, Node)]
        ins_of[nd.id] = ins
        for c in ins:
            deps[c.id].append(nd)
    outset = {o.id for o in outputs}
    uses = {nd.id: len(deps[nd.id]) + (1 if nd.id in outset else 0) for nd in nodes}
    indeg = {nd.id: len(ins_of[nd.id]) for nd in nodes}
    ready = [nd for nd in nodes if indeg[nd.id] == 0]
    order = []
    while ready:
        if SCHED_VARIANT == "belady":
            # Belady-window tiebreak: among equal freed-counts prefer the node whose value will be
            # consumed SOONEST (min remaining-indegree over its consumers) — shortest live range first.
            def score(nd):
                freed = sum(1 for c in ins_of[nd.id] if uses[c.id] == 1)
                near = min((indeg[u.id] - 1 for u in deps[nd.id]), default=0)
                return (freed, -near, -nd.id)
        else:
            def score(nd):
                freed = sum(1 for c in ins_of[nd.id] if uses[c.id] == 1)
                return (freed, -nd.id)

        ready.sort(key=score, reverse=True)
        nd = ready.pop(0)
        order.append(nd)
        for c in ins_of[nd.id]:
            uses[c.id] -= 1
        for u in deps[nd.id]:
            indeg[u.id] -= 1
            if indeg[u.id] == 0:
                ready.append(u)
    return order


# ---- the emitters: one body on codelet_lanes.hpp's lanes (the hier_codelets.hpp house style) ----
# Every body runs a tile of kTile columns (four f64, eight f32) a step: fft_codegen_split.py drives it on the lanes, a
# column at a time on scalars, a tile above the portable level and two tiles at avx512, so every column sees the same
# operations on every level. A body computes whole tiles only: every batch it is given is a multiple of kTile.
_PREC = {
    "f64": ("f64", "V(0.0)", lambda x: f"V({x!r})", 4),
    "f32": ("f32", "V(0.0F)", lambda x: f"V(static_cast<crd::f32>({x!r}))", 8),
}


def _render_node(nd, prec, batch_var, indent="        ", soa_in=False, load=None):
    """One scheduled node: loads (interleaved Complex rows, AoSoA block rows of `b2` T when soa_in, or the lines
    `load(value, input)` gives) and arithmetic; no stores."""
    tname, zero, cst = prec
    v = f"n{nd.id}"
    if nd.op == "input":
        if load is not None:
            return [indent + line for line in load(v, nd.a)]
        if soa_in:
            return [f"{indent}V {v}r, {v}i; simd::load_block(inb + {nd.a} * b2, t, {v}r, {v}i);"]
        return [
            f"{indent}V {v}r, {v}i; simd::load_complex_deinterleaved("
            f"reinterpret_cast<const crd::{tname}*>(in + {nd.a} * {batch_var} + t), {v}r, {v}i);"
        ]
    if nd.op in ("add", "sub"):
        a, c = f"n{nd.a.id}", f"n{nd.b.id}"
        op = "+" if nd.op == "add" else "-"
        return [f"{indent}const V {v}r = {a}r {op} {c}r, {v}i = {a}i {op} {c}i;"]
    a = f"n{nd.a.id}"
    if nd.op == "neg":
        # `0 - x`, not unary minus: MSVC keeps it, and it gives +0 for a -0 input on every level.
        return [f"{indent}const V {v}r = {zero} - {a}r, {v}i = {zero} - {a}i;"]
    if nd.op == "muli":  # +i*z = (-zi, zr)
        return [f"{indent}const V {v}r = {zero} - {a}i, {v}i = {a}r;"]
    if nd.op == "mulni":  # -i*z = (zi, -zr)
        return [f"{indent}const V {v}r = {a}i, {v}i = {zero} - {a}r;"]
    assert nd.op == "cmul", nd.op
    wr, wi = nd.c
    # re = wr*ar - wi*ai (fnmadd), im = wi*ar + wr*ai (fma): two products and two single-rounded fmas.
    return [
        f"{indent}const V {v}r = simd::fnmadd({cst(wi)}, {a}i, {cst(wr)} * {a}r), "
        f"{v}i = simd::fma({cst(wi)}, {a}r, {cst(wr)} * {a}i);"
    ]


def _build_dag(N, seed):
    global _TABLE, _NODES
    _TABLE, _NODES = {}, []
    xs = [inp(i) for i in range(N)]
    outs = fft_dag(xs)
    # numpy gate: 8 random vectors, rel err < 1e-12 (the DAG itself is exact; f32 rounding happens in C++)
    rng = np.random.default_rng(seed + N)
    for _ in range(8):
        xv = rng.standard_normal(N) + 1j * rng.standard_normal(N)
        got = np.array(evaluate(outs, list(xv)))
        ref = np.fft.fft(xv)
        rel = np.max(np.abs(got - ref)) / (1.0 + np.max(np.abs(ref)))
        assert rel < 1e-12, f"N={N} DAG validation FAILED rel={rel}"
    return outs


def _kernel(sig, prec_key, bound, invariant, tile_locals, body):
    """A codelet: its signature, the lanes prologue with the invariant locals, and one tile loop over `bound`."""
    tname, tile = _PREC[prec_key][0], _PREC[prec_key][3]
    out = list(sig) + [
        "{",
        f"    using V = crd::hesap::fft::lanes::Lane<crd::{tname}>;",
        "    namespace simd = crd::hesap::fft::lanes;",
    ]
    out += [f"    {line}" for line in invariant]
    out += [f"    for (crd::usize t = 0; t + {tile} <= {bound}; t += {tile})", "    {"]
    out += [f"        {line}" for line in tile_locals]
    return "\n".join(out + body + ["    }", "}"])


def _prec(prec_key):
    tname, zero, cst, _ = _PREC[prec_key]
    return tname, (tname, zero, cst)


def emit_batched(N, name, prec_key):
    """Batched N-point leaf over interleaved Complex rows in[j*b + t] -> out[k*b + t]. In-place-safe: a step loads
    every input before it stores an output."""
    tname, prec = _prec(prec_key)
    outs = _build_dag(N, 1407)
    order = schedule(outs)
    sig = [
        f"void {name}(const crd::hesap::Complex<crd::{tname}>* in,",
        f"    crd::hesap::Complex<crd::{tname}>* out, crd::usize b) noexcept",
    ]
    body = []
    for nd in order:
        body += _render_node(nd, prec, "b")
    for k, o in enumerate(outs):
        body.append(
            f"        simd::store_complex_interleaved(reinterpret_cast<crd::{tname}*>(out + {k} * b + t), "
            f"n{o.id}r, n{o.id}i);"
        )
    return _kernel(sig, prec_key, "b", [], [], body)


def _interleave_stores(order, outs, group_lanes=0):
    """STORE-EARLY scheduling (2026-07-04 spill crush): the AoSoA pipeline kernels have DISJOINT in/out buffers, so
    each output store is emitted the moment its value completes, freeing the register instead of holding all N
    outputs live to the end (the measured 44K-spill mechanism). With group_lanes, outputs are stored in transpose
    groups of that size, a group once its last member is computed. Returns the scheduled nodes with ('store', k) or
    ('store_group', g) items between them."""
    from collections import defaultdict

    outs_of_node = defaultdict(list)
    for k, o in enumerate(outs):
        outs_of_node[o.id].append(k)
    items = []
    if group_lanes:
        remaining = {g: {outs[g * group_lanes + l].id for l in range(group_lanes)}
                     for g in range(len(outs) // group_lanes)}
        done = set()
        for nd in order:
            items.append(nd)
            done.add(nd.id)
            for g, members in remaining.items():
                if members and members <= done:
                    items.append(("store_group", g))
                    remaining[g] = set()
    else:
        for nd in order:
            items.append(nd)
            items += [("store", k) for k in outs_of_node.get(nd.id, ())]
    return items


def _emit_stage1(N1, name, prec_key, factored):
    """AoSoA stage 1 (crush pass 2026-07-04): interleaved Complex in (the ONE deinterleave), leaf, fma twiddle and a
    transposed store of each group of a tile of outputs into the AoSoA rows ([L x re | L x im] blocks, L = kTile), so
    no interleave shuffles on the store side and one stream per row downstream. The full table is [k*n2 + t]; the
    FACTORED one (`factored`) gives W_n^{k*u} = hi[k*UH + u>>msh] * lo[(k<<msh) + (u&(M-1))] from two L1-resident
    tables (M = 1<<msh at least a two-tile step, UH = n2>>msh) instead of streaming as many table bytes as data every
    call, for two more fmas an output; the index split is exact."""
    tname, prec = _prec(prec_key)
    lanes = _PREC[prec_key][3]
    outs = _build_dag(N1, 2707)
    order = schedule(outs)
    if factored:
        sig = [
            f"void {name}(const crd::hesap::Complex<crd::{tname}>* in,",
            f"    crd::{tname}* outb, crd::usize n2, const crd::{tname}* lor, const crd::{tname}* loi,",
            f"    const crd::{tname}* hir, const crd::{tname}* hii, crd::u32 msh) noexcept",
        ]
        invariant = ["const crd::usize uhc = n2 >> msh;"]
        tile_locals = ["const crd::usize uh = t >> msh;", "const crd::usize ul = t & ((crd::usize{1} << msh) - 1U);"]
    else:
        sig = [
            f"void {name}(const crd::hesap::Complex<crd::{tname}>* in,",
            f"    crd::{tname}* outb, crd::usize n2, const crd::{tname}* twr,",
            f"    const crd::{tname}* twi) noexcept",
        ]
        invariant = []
        tile_locals = []

    def group_block(g):
        k0 = g * lanes
        ids = [outs[k0 + l].id for l in range(lanes)]
        block = ["        {"]
        for l in range(lanes):
            k = k0 + l
            if factored:
                block.append(f"            const V h{l}r = V(hir[{k} * uhc + uh]), h{l}i = V(hii[{k} * uhc + uh]);")
                block.append(
                    f"            const V g{l}r = simd::load<V>(lor + ((crd::usize{{{k}}} << msh) + ul)), "
                    f"g{l}i = simd::load<V>(loi + ((crd::usize{{{k}}} << msh) + ul));"
                )
                block.append(
                    f"            const V w{l}r = simd::fnmadd(h{l}i, g{l}i, h{l}r * g{l}r), "
                    f"w{l}i = simd::fma(h{l}i, g{l}r, h{l}r * g{l}i);"
                )
            else:
                block.append(
                    f"            const V w{l}r = simd::load<V>(twr + {k} * n2 + t), "
                    f"w{l}i = simd::load<V>(twi + {k} * n2 + t);"
                )
        for l in range(lanes):
            block.append(
                f"            const V x{l}r = simd::fnmadd(w{l}i, n{ids[l]}i, n{ids[l]}r * w{l}r), "
                f"x{l}i = simd::fma(w{l}i, n{ids[l]}r, n{ids[l]}i * w{l}r);"
            )
        for part, off in (("r", 2 * k0), ("i", 2 * k0 + lanes)):
            args = ", ".join(f"x{l}{part}" for l in range(lanes))
            block.append(f"            simd::store_transposed(outb + t * {2 * N1} + {off}, {2 * N1}, {args});")
        block.append("        }")
        return block

    body = []
    for item in _interleave_stores(order, outs, group_lanes=lanes):
        if isinstance(item, tuple):
            body += group_block(item[1])
        else:
            body += _render_node(item, prec, "n2")
    return _kernel(sig, prec_key, "n2", invariant, tile_locals, body)


def emit_batched_sc(N, name, prec_key):
    """AoSoA final leaf: block loads (no shuffles, one stream a row), DAG, interleaved store (the ONE reinterleave).
    NOT in-place (AoSoA in vs Complex out, always disjoint in the sh/ds pipelines)."""
    tname, prec = _prec(prec_key)
    outs = _build_dag(N, 1407)
    order = schedule(outs)
    sig = [
        f"void {name}(const crd::{tname}* inb,",
        f"    crd::hesap::Complex<crd::{tname}>* out, crd::usize b) noexcept",
    ]
    body = []
    for item in _interleave_stores(order, outs):
        if isinstance(item, tuple):
            o = outs[item[1]]
            body.append(
                f"        simd::store_complex_interleaved(reinterpret_cast<crd::{tname}*>(out + {item[1]} * b + t), "
                f"n{o.id}r, n{o.id}i);"
            )
        else:
            body += _render_node(item, prec, "b", soa_in=True)
    return _kernel(sig, prec_key, "b", ["const crd::usize b2 = 2 * b;"], [], body)


