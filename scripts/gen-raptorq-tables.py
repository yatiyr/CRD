#!/usr/bin/env python3
"""Generate engine/numerics/hesap-net/src/raptorq_tables.inc from the text of RFC 6330.

The degree distribution (Table 1), the random number arrays V0 to V3 (section 5.5) and the systematic indices (Table 2)
are 1,500 numbers no one should type. The RFC is fetched from the RFC Editor and checked against its SHA-256, or read
from --rfc; --check compares the committed file instead of writing it.
"""

import argparse
import hashlib
import pathlib
import re
import sys
import urllib.request

RFC_URL = 'https://www.rfc-editor.org/rfc/rfc6330.txt'
RFC_SHA256 = '87f6da89cc325987cb2910d1c124f74eaeac5c86a83f962cf347c0cc66321ace'
OUTPUT = pathlib.Path(__file__).resolve().parents[1] / 'engine/numerics/hesap-net/src/raptorq_tables.inc'
WIDTH = 120
PAGE_FURNITURE = re.compile(r'^(Luby, et al\.|RFC 6330 )')


def rfc_lines(path):
    """The RFC's lines without its page headers and footers, its SHA-256 checked."""
    if path:
        data = pathlib.Path(path).read_bytes()
    else:
        with urllib.request.urlopen(RFC_URL, timeout=60) as response:
            data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != RFC_SHA256:
        sys.exit(f'gen-raptorq-tables: RFC 6330 has SHA-256 {digest}, expected {RFC_SHA256}')
    text = data.decode('ascii', errors='strict').replace('\r\n', '\n').replace('\f', '')
    return [line for line in text.split('\n') if not PAGE_FURNITURE.match(line)]


def section(lines, start, end):
    """The lines between the headings that begin with `start` and `end`, after the table of contents."""
    begin = next(i for i, line in enumerate(lines) if line.startswith(start) and '. . .' not in line)
    stop = next(i for i in range(begin + 1, len(lines)) if lines[i].startswith(end) and '. . .' not in lines[i])
    return lines[begin + 1:stop]


def random_array(lines, name, following):
    numbers = [int(n) for line in section(lines, f'5.5.{int(name[1:]) + 1}.  The Table {name}', following)
               for n in re.findall(r'\d+', line)]
    if len(numbers) != 256 or max(numbers) >= 2 ** 32:
        sys.exit(f'gen-raptorq-tables: {name} holds {len(numbers)} numbers')
    return numbers


def degree_table(lines):
    cells = {}
    for line in section(lines, '5.3.5.2.', '5.3.5.3.'):
        row = re.findall(r'\|\s*(\d+)\s*\|\s*(\d+)\s*(?=\|)', line)
        for index, value in row:
            cells[int(index)] = int(value)
    if sorted(cells) != list(range(31)) or cells[0] != 0 or cells[30] != 2 ** 20:
        sys.exit('gen-raptorq-tables: Table 1 is not f[0] to f[30]')
    return [cells[d] for d in range(31)]


def systematic_table(lines):
    rows = []
    for line in section(lines, '5.6.  Systematic Indices', '5.7.  Operating'):
        match = re.fullmatch(r'\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|\s*', line)
        if match:
            rows.append(tuple(int(n) for n in match.groups()))
    if len(rows) != 477 or rows[0][0] != 10 or rows[-1][0] != 56403:
        sys.exit(f'gen-raptorq-tables: Table 2 holds {len(rows)} rows')
    return rows


def wrapped(items, indent='    '):
    """`items`, comma separated, filled to the column limit."""
    out = []
    line = indent
    for item in items:
        piece = f'{item},'
        if len(line) + len(piece) + 1 > WIDTH:
            out.append(line.rstrip())
            line = indent
        line += piece + ' '
    out.append(line.rstrip())
    return '\n'.join(out)


def render(lines):
    arrays = [random_array(lines, 'V0', '5.5.2.'), random_array(lines, 'V1', '5.5.3.'),
              random_array(lines, 'V2', '5.5.4.'), random_array(lines, 'V3', '5.6.')]
    degree = degree_table(lines)
    systematic = systematic_table(lines)
    parts = [
        '// Generated by scripts/gen-raptorq-tables.py from the text of RFC 6330 (SHA-256 '
        f'{RFC_SHA256[:16]}...); do not edit.\n',
        '// Table 1: Deg[v] = d for f[d - 1] <= v < f[d], before the bound by W - 2.\n'
        f'constexpr u32 kDegreeBounds[31] = {{\n{wrapped(f"{n}U" for n in degree)}\n}};\n',
        '// Section 5.5: the arrays V0 to V3 of Rand[y, i, m].\nconstexpr u32 kRandomArrays[4][256] = {',
    ]
    for array in arrays:
        parts.append(f'    {{\n{wrapped((f"{n}U" for n in array), " " * 8)}\n    }},')
    parts.append('};\n')
    parts.append("// Table 2: K', J(K'), S(K'), H(K') and W(K').\n"
                 f'constexpr RaptorqSystematicRow kSystematicRows[{len(systematic)}] = {{')
    parts.append(wrapped(('{' + ', '.join(f'{n}U' for n in row) + '}' for row in systematic)))
    parts.append('};\n')
    return '\n'.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rfc', help='a local copy of rfc6330.txt instead of the RFC Editor')
    parser.add_argument('--check', action='store_true', help='compare with the committed file')
    args = parser.parse_args()
    text = render(rfc_lines(args.rfc))
    if args.check:
        if OUTPUT.read_text(encoding='ascii') != text:
            sys.exit(f'gen-raptorq-tables: {OUTPUT} differs from the RFC')
        return
    OUTPUT.write_bytes(text.encode('ascii'))


if __name__ == '__main__':
    main()
