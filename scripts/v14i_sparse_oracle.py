def write_coo_bin(path, idx, val, shape):
    """header: u64 rank, u64 shape[rank], u64 nnz; then mode-major u32 index
    planes; then f64 values."""
    rank = len(shape)
    with open(path, "wb") as f:
        f.write(struct.pack("<Q", rank))
        f.write(struct.pack("<{}Q".format(rank), *shape))
        f.write(struct.pack("<Q", len(val)))
        for m in range(rank):
            f.write(idx[:, m].astype(np.uint32).tobytes())
        f.write(val.astype(np.float64).tobytes())


def write_mat_bin(path, a):
    with open(path, "wb") as f:
        f.write(struct.pack("<QQ", a.shape[0], a.shape[1]))
        f.write(np.ascontiguousarray(a, dtype=np.float64).tobytes())


def best_of(fn, n=5):
    best = None
    for _ in range(n):
        t0 = time.perf_counter()
        r = fn()
        dt = (time.perf_counter() - t0) * 1e3
        best = dt if best is None or dt < best else best
    return best, r


def run_bench():
    import scipy.sparse as sp
    import torch
    torch.set_num_threads(1)

    os.makedirs(BENCH_DIR, exist_ok=True)
    rng = np.random.default_rng(SEED + 1)
    I = J = K = 1024
    NNZ_RAW = 5_000_000
    R = 16
    F = 16
    shape = (I, J, K)

    print("== bench corpus: shape ({},{},{}), raw nnz {}, R={}, F={} ==".format(I, J, K, NNZ_RAW, R, F))
    flat = rng.choice(I * J * K, size=NNZ_RAW, replace=False)
    idx = np.stack(np.unravel_index(flat, shape), axis=1).astype(np.uint32)
    val = rng.uniform(-1.0, 1.0, size=NNZ_RAW)
    idx, val = canonicalize(idx, val, shape)
    nnz = len(val)
    print("canonical nnz:", nnz)

    fb = rng.uniform(-1.0, 1.0, size=(J, R))
    fc = rng.uniform(-1.0, 1.0, size=(K, R))
    u1 = rng.uniform(-1.0, 1.0, size=(J, F))
    u2 = rng.uniform(-1.0, 1.0, size=(K, F))

    # second tensor for elementwise (same size, ~50% pattern overlap)
    keep = rng.random(nnz) < 0.5
    flat2 = rng.choice(I * J * K, size=NNZ_RAW // 2, replace=False)
    idx2 = np.concatenate([idx[keep],
                           np.stack(np.unravel_index(flat2, shape), axis=1).astype(np.uint32)], axis=0)
    val2 = rng.uniform(-1.0, 1.0, size=len(idx2))
    idx2, val2 = canonicalize(idx2, val2, shape)

    write_coo_bin(os.path.join(BENCH_DIR, "v14i_t1.bin"), idx, val, shape)
    write_coo_bin(os.path.join(BENCH_DIR, "v14i_t2.bin"), idx2, val2, shape)
    write_mat_bin(os.path.join(BENCH_DIR, "v14i_fb.bin"), fb)
    write_mat_bin(os.path.join(BENCH_DIR, "v14i_fc.bin"), fc)
    write_mat_bin(os.path.join(BENCH_DIR, "v14i_u1.bin"), u1)
    write_mat_bin(os.path.join(BENCH_DIR, "v14i_u2.bin"), u2)
    # SPLATT text format (1-indexed .tns)
    tns = os.path.join(BENCH_DIR, "v14i_t1.tns")
    if not os.path.exists(tns):
        with open(tns, "w") as f:
            for t in range(nnz):
                f.write("{} {} {} {:.17g}\n".format(idx[t, 0] + 1, idx[t, 1] + 1, idx[t, 2] + 1, val[t]))
    print("bench data written to", BENCH_DIR)

    i32 = idx.astype(np.int64)
    # ---- scipy peers (prep outside timers: csr unfoldings) ----
    x0 = sp.csr_matrix((val, (i32[:, 0], i32[:, 1] * K + i32[:, 2])), shape=(I, J * K))
    x1r = sp.csr_matrix((val, (i32[:, 0] * K + i32[:, 2], i32[:, 1])), shape=(I * K, J))  # rows=(i,k), cols=j
    kr = np.einsum("jr,kr->jkr", fb, fc).reshape(J * K, R)

    t, m_sci = best_of(lambda: x0 @ kr)
    print("scipy  mttkrp-mode0      : {:9.2f} ms   checksum {:.17g}".format(t, float(m_sci.sum())))

    def sci_ttm1():
        y = x1r @ u1                       # [(i,k), f]
        y = y.reshape(I, K, F)
        return np.ascontiguousarray(np.moveaxis(y, 2, 1))  # fold to (i, f, k)
    t, y_sci = best_of(sci_ttm1)
    print("scipy  ttm-mode1 (fold)  : {:9.2f} ms   checksum {:.17g}".format(t, float(y_sci.sum())))

    def sci_ttm2():
        # mode-2 (last): unfold rows=(i,j), cols=k -> result [(i,j), f] IS the folded (i,j,f)
        return x2r @ u2
    x2r = sp.csr_matrix((val, (i32[:, 0] * J + i32[:, 1], i32[:, 2])), shape=(I * J, K))
    t, y2_sci = best_of(sci_ttm2)
    print("scipy  ttm-mode2         : {:9.2f} ms   checksum {:.17g}".format(t, float(y2_sci.sum())))

    i32b = idx2.astype(np.int64)
    a2d = sp.csr_matrix((val, (i32[:, 0], i32[:, 1] * K + i32[:, 2])), shape=(I, J * K))
    b2d = sp.csr_matrix((val2, (i32b[:, 0], i32b[:, 1] * K + i32b[:, 2])), shape=(I, J * K))
    t, s_add = best_of(lambda: a2d + b2d)
    print("scipy  sparse add        : {:9.2f} ms   checksum {:.17g}".format(t, float(s_add.sum())))
    t, s_mul = best_of(lambda: a2d.multiply(b2d))
    print("scipy  sparse mul        : {:9.2f} ms   checksum {:.17g}".format(t, float(s_mul.sum())))
    t, s_sum = best_of(lambda: a2d.sum())
    print("scipy  reduce sum-total  : {:9.2f} ms   checksum {:.17g}".format(t, float(s_sum)))
    t, s_sum0 = best_of(lambda: np.asarray(a2d.sum(axis=1)).ravel())
    print("scipy  reduce sum-mode0  : {:9.2f} ms   checksum {:.17g}".format(t, float(s_sum0.sum())))
    t, s_max0 = best_of(lambda: a2d.max(axis=1).toarray().ravel())
    print("scipy  reduce max-mode0  : {:9.2f} ms   checksum {:.17g}".format(t, float(s_max0.sum())))

    # ---- torch peers (sparse csr where supported, matched 1 thread) ----
    tx0 = torch.sparse_coo_tensor(
        np.stack([i32[:, 0], i32[:, 1] * K + i32[:, 2]]), val, (I, J * K)).coalesce().to_sparse_csr()
    tkr = torch.from_numpy(kr)
    t, tm = best_of(lambda: torch.mm(tx0, tkr))
    print("torch  mttkrp-mode0      : {:9.2f} ms   checksum {:.17g}".format(t, float(tm.sum())))

    tx1 = torch.sparse_coo_tensor(
        np.stack([i32[:, 0] * K + i32[:, 2], i32[:, 1]]), val, (I * K, J)).coalesce().to_sparse_csr()
    tu1 = torch.from_numpy(u1)

    def tor_ttm1():
        y = torch.mm(tx1, tu1).reshape(I, K, F)
        return y.permute(0, 2, 1).contiguous()
    t, ty = best_of(tor_ttm1)
    print("torch  ttm-mode1 (fold)  : {:9.2f} ms   checksum {:.17g}".format(t, float(ty.sum())))

    tx2 = torch.sparse_coo_tensor(
        np.stack([i32[:, 0] * J + i32[:, 1], i32[:, 2]]), val, (I * J, K)).coalesce().to_sparse_csr()
    tu2 = torch.from_numpy(u2)
    t, ty2 = best_of(lambda: torch.mm(tx2, tu2))
    print("torch  ttm-mode2         : {:9.2f} ms   checksum {:.17g}".format(t, float(ty2.sum())))

    ta = torch.sparse_coo_tensor(i32.T, val, shape).coalesce()
    tb = torch.sparse_coo_tensor(i32b.T, val2, shape).coalesce()
    t, t_add = best_of(lambda: torch.add(ta, tb).coalesce())
    print("torch  sparse add        : {:9.2f} ms   checksum {:.17g}".format(t, float(t_add.values().sum())))
    try:
        t, t_mul = best_of(lambda: torch.mul(ta, tb).coalesce())
        print("torch  sparse mul        : {:9.2f} ms   checksum {:.17g}".format(t, float(t_mul.values().sum())))
    except Exception as e:  # noqa: BLE001 — peer capability probe
        print("torch  sparse mul        : N/A ({})".format(type(e).__name__))
    t, t_sum = best_of(lambda: torch.sparse.sum(ta))
    print("torch  reduce sum-total  : {:9.2f} ms   checksum {:.17g}".format(t, float(t_sum)))
    t, t_sum0 = best_of(lambda: torch.sparse.sum(ta, dim=(1, 2)))
    print("torch  reduce sum-mode0  : {:9.2f} ms   checksum {:.17g}".format(t, float(t_sum0.to_dense().sum())))
    print("(torch sparse max reduction: unsupported by torch.sparse — N/A row)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bench", action="store_true")
    args = ap.parse_args()
    if args.bench:
        run_bench()
    else:
        generate_inc()


if __name__ == "__main__":
    sys.exit(main())
