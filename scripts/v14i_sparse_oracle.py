#!/usr/bin/env python3
# v14-i SPARSE tensor oracle — reconstruct-verify-first (SANITY doctrine).
#
# Default mode: generate tests/hesap-tensor/ref_sparse.inc — frozen corpora
# (random COO rank-3/4 with duplicate raw triplets, a structured FROSTT-like
# fiber pattern with an all-empty mode-0 slice, a dense-as-sparse cube) plus
# expected values computed with numpy DENSE semantics (the scipy/torch
# reference semantics): canonical dedup COO, MTTKRP per mode, mode-n
# sparse x dense contraction (tensor layout, mode replaced), sparse
# elementwise add/mul (union/intersection) + sparse x dense hadamard +
# sparse + dense -> dense, and sum/max reductions (total + per mode,
# implicit zeros participate in max exactly like a densified array).
#
# --bench: write the big bench corpora as binary files under
# $HOME/cerid-bench-data/ (shared bit-exact with the C++ harness) and run the
# python peer timings (scipy.sparse csr + torch.sparse, matched 1 thread,
# best-of-5). Run pinned: taskset -c 4 python3 scripts/v14i_sparse_oracle.py --bench
#
# Values are emitted as u64 hex bit patterns (the house ref_*.inc convention)
# so the C++ side consumes the exact bits numpy used.
