def f64_bits(a):
    return np.asarray(a, dtype=np.float64).reshape(-1).view(np.uint64)


class Inc:
    def __init__(self):
        self.lines = [
            "// GENERATED by scripts/v14i_sparse_oracle.py -- numpy {} reference bits.".format(np.__version__),
            "// DO NOT hand-edit; regenerate. Plain C arrays; f64 values as u64 bit patterns.",
            "#pragma once",
            "#include <crd/core/types.hpp>",
            "",
        ]

    def u32(self, name, arr):
        arr = np.asarray(arr, dtype=np.uint64).reshape(-1)
        self._arr(name, "crd::u32", ["{}U".format(int(v)) for v in arr], 16)

    def u64(self, name, arr):
        arr = np.asarray(arr, dtype=np.uint64).reshape(-1)
        self._arr(name, "crd::u64", ["{}ULL".format(int(v)) for v in arr], 12)

    def f64(self, name, arr):
        bits = f64_bits(arr)
        self._arr(name, "crd::u64", ["0x{:016X}ULL".format(int(v)) for v in bits], 6)

    def scalar_u32(self, name, v):
        self.lines.append("inline constexpr crd::u32 {} = {}U;".format(name, int(v)))

    def _arr(self, name, ctype, toks, per_line):
        self.lines.append("inline const {} {}[] = {{".format(ctype, name))
        for i in range(0, len(toks), per_line):
            self.lines.append("    " + ", ".join(toks[i:i + per_line]) + ",")
        if not toks:
            self.lines.append("    0,  // empty array placeholder (count constant is 0)")
        self.lines.append("};")

    def write(self, path):
        with open(path, "w", newline="\n") as f:
            f.write("\n".join(self.lines) + "\n")


MTT_EINSUM = {
    (3, 0): "ijk,jr,kr->ir", (3, 1): "ijk,ir,kr->jr", (3, 2): "ijk,ir,jr->kr",
    (4, 0): "ijkl,jr,kr,lr->ir", (4, 2): "ijkl,ir,jr,lr->kr",
}
TTM_EINSUM = {
    (3, 0): "ijk,if->fjk", (3, 1): "ijk,jf->ifk", (3, 2): "ijk,kf->ijf",
    (4, 3): "ijkl,lf->ijkf",
}


def emit_corpus(inc, rng, tag, shape, idx_raw, val_raw, fac_r, mtt_modes, ttm_modes,
                sum_modes, max_modes, totals):
    rank = len(shape)
    idx, val = canonicalize(idx_raw, val_raw, shape)
    dense = densify(idx, val, shape)
    inc.scalar_u32("kSp{}Rank".format(tag), rank)
    inc.u64("kSp{}Shape".format(tag), np.array(shape, dtype=np.uint64))
    inc.scalar_u32("kSp{}RawNnz".format(tag), len(val_raw))
    inc.u32("kSp{}RawIdx".format(tag), idx_raw.reshape(-1))          # triplet-major
    inc.f64("kSp{}RawVal".format(tag), val_raw)
    inc.scalar_u32("kSp{}Nnz".format(tag), len(val))
    inc.u32("kSp{}Idx".format(tag), idx.T.reshape(-1))               # mode-major planes
    inc.f64("kSp{}Val".format(tag), val)

    facs = [rng.uniform(-1.0, 1.0, size=(shape[m], fac_r)) for m in range(rank)]
    inc.scalar_u32("kSp{}FacR".format(tag), fac_r)
    for m in range(rank):
        inc.f64("kSp{}Fac{}".format(tag, m), facs[m])
    for m in mtt_modes:
        args = [facs[q] for q in range(rank) if q != m]
        out = np.einsum(MTT_EINSUM[(rank, m)], dense, *args)
        inc.f64("kSp{}Mtt{}".format(tag, m), out)
    for m, fdim in ttm_modes:
        u = rng.uniform(-1.0, 1.0, size=(shape[m], fdim))
        out = np.einsum(TTM_EINSUM[(rank, m)], dense, u)
        inc.scalar_u32("kSp{}TtmF{}".format(tag, m), fdim)
        inc.f64("kSp{}TtmU{}".format(tag, m), u)
        inc.f64("kSp{}Ttm{}".format(tag, m), out)
    for m in sum_modes:
        axes = tuple(q for q in range(rank) if q != m)
        inc.f64("kSp{}SumMode{}".format(tag, m), dense.sum(axis=axes))
    for m in max_modes:
        axes = tuple(q for q in range(rank) if q != m)
        inc.f64("kSp{}MaxMode{}".format(tag, m), dense.max(axis=axes))
    if totals:
        inc.f64("kSp{}SumTotal".format(tag), [dense.sum()])
        inc.f64("kSp{}MaxTotal".format(tag), [dense.max()])
    return idx, val, dense


def generate_inc():
    rng = np.random.default_rng(SEED)
    inc = Inc()

    # R3a: rank-3 random with duplicate raw triplets
    shape3 = (14, 12, 10)
    idx_raw, val_raw = make_random_coo(rng, shape3, n_unique=360, n_raw=400)
    r3a_idx, r3a_val, r3a_dense = emit_corpus(
        inc, rng, "R3a", shape3, idx_raw, val_raw, fac_r=8,
        mtt_modes=[0, 1, 2], ttm_modes=[(0, 6), (1, 5)],
        sum_modes=[0, 1, 2], max_modes=[0, 1, 2], totals=True)

    # R3b: second rank-3 tensor for elementwise; pattern overlaps R3a
    n_overlap = 120
    pick = rng.choice(len(r3a_val), size=n_overlap, replace=False)
    fresh_flat = rng.choice(int(np.prod(shape3)), size=260, replace=False)
    fresh = np.stack(np.unravel_index(fresh_flat, shape3), axis=1).astype(np.uint32)
    idx_raw_b = np.concatenate([r3a_idx[pick].astype(np.uint32), fresh], axis=0)
    val_raw_b = rng.uniform(-1.0, 1.0, size=len(idx_raw_b))
    r3b_idx, r3b_val, r3b_dense = emit_corpus(
        inc, rng, "R3b", shape3, idx_raw_b, val_raw_b, fac_r=8,
        mtt_modes=[], ttm_modes=[], sum_modes=[], max_modes=[], totals=False)

    # elementwise expectations (union add / intersection mul / dense ops)
    a_set = {tuple(t) for t in r3a_idx}
    b_set = {tuple(t) for t in r3b_idx}
    union = sorted(a_set | b_set)
    inter = sorted(a_set & b_set)
    add_idx = np.array(union, dtype=np.uint32)
    add_val = np.array([r3a_dense[t] + r3b_dense[t] for t in union])
    mul_idx = np.array(inter, dtype=np.uint32)
    mul_val = np.array([r3a_dense[t] * r3b_dense[t] for t in inter])
    inc.scalar_u32("kSpEwAddNnz", len(add_val))
    inc.u32("kSpEwAddIdx", add_idx.T.reshape(-1))
    inc.f64("kSpEwAddVal", add_val)
    inc.scalar_u32("kSpEwMulNnz", len(mul_val))
    inc.u32("kSpEwMulIdx", mul_idx.T.reshape(-1))
    inc.f64("kSpEwMulVal", mul_val)
    dmat = rng.uniform(-1.0, 1.0, size=shape3)
    inc.f64("kSpEwDenseD", dmat)
    hadamard = np.array([r3a_dense[tuple(t)] * dmat[tuple(t)] for t in r3a_idx])
    inc.f64("kSpEwMulDenseVal", hadamard)   # pattern of R3a canonical
    inc.f64("kSpEwAddDenseOut", r3a_dense + dmat)

    # R4a: rank-4 random with dups
    shape4 = (9, 8, 7, 6)
    idx_raw4, val_raw4 = make_random_coo(rng, shape4, n_unique=320, n_raw=350)
    emit_corpus(inc, rng, "R4a", shape4, idx_raw4, val_raw4, fac_r=8,
                mtt_modes=[0, 2], ttm_modes=[(3, 4)],
                sum_modes=[1], max_modes=[2], totals=True)

    # Fro: structured FROSTT-like fibers, mode-0 slice 7 completely empty
    shapef = (32, 24, 16)
    idx_rawf, val_rawf = make_frostt_like(rng, shapef, n_fibers=90, skip_mode0=7)
    emit_corpus(inc, rng, "Fro", shapef, idx_rawf, val_rawf, fac_r=16,
                mtt_modes=[0, 1], ttm_modes=[],
                sum_modes=[0], max_modes=[0], totals=True)

    # Dns: dense-as-sparse cube (every cell present -> max branches without
    # implicit zeros; negative maxima possible)
    shaped = (4, 3, 2)
    cells = np.stack(np.unravel_index(np.arange(24), shaped), axis=1).astype(np.uint32)
    valsd = rng.uniform(-1.0, -0.05, size=24)  # all negative: max_total < 0
    emit_corpus(inc, rng, "Dns", shaped, cells, valsd, fac_r=3,
                mtt_modes=[0], ttm_modes=[(2, 3)],
                sum_modes=[], max_modes=[0], totals=True)

    inc.write(OUT_INC)
    print("wrote", OUT_INC, "({} lines)".format(len(inc.lines)))


