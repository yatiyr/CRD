def canonicalize(idx_raw, val_raw, shape):
    """Stable lexicographic sort (mode 0 major) + duplicate sum in insertion
    order (np.lexsort is stable; reduceat sums left-to-right) — the exact
    contract of the C++ builder, so canonical values are BIT-comparable."""
    rank = len(shape)
    keys = tuple(idx_raw[:, m] for m in range(rank - 1, -1, -1))
    order = np.lexsort(keys)
    si = idx_raw[order]
    sv = val_raw[order]
    if len(sv) == 0:
        return si.reshape(0, rank), sv
    new = np.ones(len(sv), dtype=bool)
    new[1:] = np.any(si[1:] != si[:-1], axis=1)
    starts = np.flatnonzero(new)
    vals = np.add.reduceat(sv, starts)
    return si[starts], vals


def densify(idx, val, shape):
    x = np.zeros(shape, dtype=np.float64)
    x[tuple(idx[:, m] for m in range(len(shape)))] = val
    return x


def make_random_coo(rng, shape, n_unique, n_raw):
    """raw triplets drawn WITH replacement from a unique cell pool -> dups."""
    total = int(np.prod(shape))
    flat = rng.choice(total, size=n_unique, replace=False)
    pool = np.stack(np.unravel_index(flat, shape), axis=1).astype(np.uint32)
    pick = rng.integers(0, n_unique, size=n_raw)
    idx_raw = pool[pick]
    val_raw = rng.uniform(-1.0, 1.0, size=n_raw)
    return idx_raw, val_raw


def make_frostt_like(rng, shape, n_fibers, skip_mode0):
    """FROSTT-like: (i,j) fiber pairs with short k runs; i zipf-skewed;
    mode-0 index `skip_mode0` left completely empty (the all-zeros-slice
    adversary)."""
    rows = []
    for _ in range(n_fibers):
        i = int(shape[0] * rng.random() ** 2.0)
        i = min(i, shape[0] - 1)
        if i == skip_mode0:
            i = (i + 1) % shape[0]
        j = int(rng.integers(0, shape[1]))
        length = int(rng.integers(2, 11))
        k0 = int(rng.integers(0, shape[2]))
        for t in range(length):
            k = (k0 + t) % shape[2]
            rows.append((i, j, k))
    idx_raw = np.array(rows, dtype=np.uint32)
    val_raw = rng.uniform(-1.0, 1.0, size=len(rows))
    return idx_raw, val_raw


