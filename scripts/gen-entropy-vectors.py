#!/usr/bin/env python3
"""Known answers for crd-compression's entropy coder (NET.3), from a restatement in Python that shares no code with it: the
coder's definition from Duda's paper, and largest-remainder normalisation over Python's unbounded integers.

  python scripts/gen-entropy-vectors.py          # writes tests/foundation/compression/generated/entropy_vectors.inc
  python scripts/gen-entropy-vectors.py --check  # fails when the committed file differs
"""
from pathlib import Path
import argparse
import random
import sys

SCALE_BITS = 12
SCALE = 1 << SCALE_BITS
LOW = 1 << 16
CONTEXTS = 4
OUTPUT = 'tests/foundation/compression/generated/entropy_vectors.inc'


def context_of(byte):
    if byte == 0:
        return 0
    if byte < 16:
        return 1
    return 2 if byte % 16 == 0 else 3


def contexts_of(data):
    return [0] + [context_of(byte) for byte in data[:-1]]


def train(samples):
    counts = [[0] * 256 for _ in range(CONTEXTS)]
    for sample in samples:
        for context, byte in zip(contexts_of(sample), sample):
            counts[context][byte] += 1
    return [normalize(row) for row in counts]


def normalize(counts):
    total = sum(counts)
    if total == 0:
        return [SCALE // 256] * 256
    frequencies = [max(1, count * SCALE // total) for count in counts]
    remainders = [count * SCALE % total for count in counts]
    while sum(frequencies) < SCALE:
        best = max(range(256), key=lambda symbol: (remainders[symbol], -symbol))
        remainders[best] = 0
        frequencies[best] += 1
    while sum(frequencies) > SCALE:
        best = max(range(256), key=lambda symbol: (frequencies[symbol], -symbol))
        frequencies[best] -= 1
    return frequencies


def starts_of(frequencies):
    starts = []
    start = 0
    for frequency in frequencies:
        starts.append(start)
        start += frequency
    return starts


def encode(model, data):
    starts = [starts_of(row) for row in model]
    state = LOW
    written = []
    for context, byte in reversed(list(zip(contexts_of(data), data))):
        frequency = model[context][byte]
        while state >= (LOW // SCALE * 256) * frequency:
            written.append(state % 256)
            state //= 256
        state = (state // frequency) * SCALE + state % frequency + starts[context][byte]
    return bytes([state >> 16, (state >> 8) & 255, state & 255] + written[::-1])


def samples():
    rng = random.Random(0x5E11)
    sparse = bytes(0 if rng.random() < 0.8 else rng.randrange(1, 16) * rng.choice((1, 16)) for _ in range(800))
    flat = bytes(rng.randrange(256) for _ in range(1000))
    return [sparse, flat[:100]]


def vectors(model):
    rng = random.Random(0xC0DE)
    inputs = [b'', b'\0', b'\xff', b'\0\0\0\0\0\0\0\0', bytes(300), bytes(range(256))]
    for length in (1, 2, 3, 7, 16, 61, 200):
        inputs.append(bytes(0 if rng.random() < 0.7 else rng.randrange(256) for _ in range(length)))
    return [(data, encode(model, data)) for data in inputs]


def array(name, data):
    lines = [f'inline constexpr crd::u8 {name}[] = {{']
    body = list(data) or [0]
    for at in range(0, len(body), 16):
        lines.append('    ' + ', '.join(f'0x{value:02X}U' for value in body[at:at + 16]) + ',')
    lines.append('};')
    return lines


def text():
    training = samples()
    model = train(training)
    lines = [f'// GENERATED by scripts/gen-entropy-vectors.py. Do not edit.', '//',
             '// A model trained on two samples, and inputs with what a restatement of the coder writes for them.', '']
    for index, sample in enumerate(training):
        lines += array(f'kTrainingSample{index}', sample)
    source = bytes(byte for row in model for frequency in row for byte in (frequency & 255, frequency >> 8))
    lines += array('kModelSource', source)
    entries = []
    for index, (data, coded) in enumerate(vectors(model)):
        lines += array(f'kInput{index}', data) + array(f'kCoded{index}', coded)
        entries.append(f'    {{{{kInput{index}, {len(data)}U}}, {{kCoded{index}, {len(coded)}U}}}},')
    lines += ['', 'struct EntropyVector', '{', '    crd::containers::ConstSpan<crd::u8> input;',
              '    crd::containers::ConstSpan<crd::u8> coded;', '};', '',
              'inline const EntropyVector kVectors[] = {', *entries, '};', '']
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parent.parent)
    arguments = parser.parse_args(argv)
    path = arguments.root / OUTPUT
    wanted = text()
    if arguments.check:
        if not path.exists() or path.read_text(encoding='utf-8') != wanted:
            print(f'gen-entropy-vectors: {OUTPUT} differs; run the script', file=sys.stderr)
            return 1
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(wanted, encoding='utf-8', newline='\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
